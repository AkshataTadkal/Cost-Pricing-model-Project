CREATE OR REPLACE VIEW FMIS_VALIDATION_COMPARISON_V2 AS
WITH last_train AS (
    SELECT
        SERIES_ID,
        REALIZED_MATERIAL_INDEX AS LAST_TRAIN_INDEX
    FROM FMIS_MODEL_DATASET_V2
    WHERE DATA_SPLIT = 'TRAIN'
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY TO_JSON(SERIES_ID)
        ORDER BY INDEX_TIMESTAMP DESC
    ) = 1
)
SELECT
    a.SERIES_ID,
    a.SERIES_KEY,
    a.INDEX_TIMESTAMP,
    a.REALIZED_MATERIAL_INDEX AS ACTUAL_MATERIAL_INDEX,
    f.FORECAST_MATERIAL_INDEX,
    f.LOWER_BOUND,
    f.UPPER_BOUND,
    l.LAST_TRAIN_INDEX AS NAIVE_FORECAST_INDEX,
    ABS(f.FORECAST_MATERIAL_INDEX - a.REALIZED_MATERIAL_INDEX)
        AS ML_ABSOLUTE_ERROR,
    ABS(l.LAST_TRAIN_INDEX - a.REALIZED_MATERIAL_INDEX)
        AS NAIVE_ABSOLUTE_ERROR,
    IFF(
        a.REALIZED_MATERIAL_INDEX BETWEEN f.LOWER_BOUND AND f.UPPER_BOUND,
        1,
        0
    ) AS INTERVAL_COVERED_FLAG
FROM FMIS_MODEL_DATASET_V2 a
JOIN FMIS_VALIDATION_FORECASTS_V2 f
  ON TO_JSON(a.SERIES_ID) = TO_JSON(f.SERIES)
 AND a.INDEX_TIMESTAMP = f.INDEX_TIMESTAMP
JOIN last_train l
  ON TO_JSON(a.SERIES_ID) = TO_JSON(l.SERIES_ID)
WHERE a.DATA_SPLIT = 'VALIDATION';

