CREATE TABLE IF NOT EXISTS DATASET_SPLIT_CONFIG (
    DATASET_NAME VARCHAR NOT NULL,
    SPLIT_VERSION VARCHAR NOT NULL,
    DATE_COLUMN_NAME VARCHAR NOT NULL,
    TRAIN_END_DATE DATE NOT NULL,
    VALIDATION_END_DATE DATE NOT NULL,
    TEST_END_DATE DATE NOT NULL,
    SPLIT_METHOD VARCHAR NOT NULL,
    STATUS VARCHAR NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    NOTES VARCHAR,
    CONSTRAINT PK_DATASET_SPLIT_CONFIG
        PRIMARY KEY (DATASET_NAME, SPLIT_VERSION)
);

MERGE INTO DATASET_SPLIT_CONFIG t
USING (
    SELECT 'CSS' DATASET_NAME, 'SPLIT_V1' SPLIT_VERSION,
           'PRODUCTION_DATE' DATE_COLUMN_NAME,
           TO_DATE('2024-12-31') TRAIN_END_DATE,
           TO_DATE('2025-06-30') VALIDATION_END_DATE,
           TO_DATE('2025-12-31') TEST_END_DATE,
           'CHRONOLOGICAL' SPLIT_METHOD,
           'ACTIVE' STATUS,
           'Synthetic development split. No random sampling.' NOTES
    UNION ALL
    SELECT 'TDS', 'SPLIT_V1', 'RUN_DATE',
           TO_DATE('2024-12-31'), TO_DATE('2025-06-30'), TO_DATE('2025-12-31'),
           'CHRONOLOGICAL', 'ACTIVE',
           'Synthetic development split. No random sampling.'
    UNION ALL
    SELECT 'BMCS', 'SPLIT_V1', 'RFQ_DATE',
           TO_DATE('2024-12-31'), TO_DATE('2025-06-30'), TO_DATE('2025-12-31'),
           'CHRONOLOGICAL', 'ACTIVE',
           'Synthetic development split. No random sampling.'
    UNION ALL
    SELECT 'FMIS', 'SPLIT_V1', 'AS_OF_DATE',
           TO_DATE('2024-10-01'), TO_DATE('2025-08-01'), TO_DATE('2026-06-01'),
           'CHRONOLOGICAL', 'ACTIVE',
           'Split by forecast as-of month, not by individual rows.'
) s
ON t.DATASET_NAME = s.DATASET_NAME
AND t.SPLIT_VERSION = s.SPLIT_VERSION
WHEN MATCHED THEN UPDATE SET
    DATE_COLUMN_NAME = s.DATE_COLUMN_NAME,
    TRAIN_END_DATE = s.TRAIN_END_DATE,
    VALIDATION_END_DATE = s.VALIDATION_END_DATE,
    TEST_END_DATE = s.TEST_END_DATE,
    SPLIT_METHOD = s.SPLIT_METHOD,
    STATUS = s.STATUS,
    NOTES = s.NOTES
WHEN NOT MATCHED THEN INSERT (
    DATASET_NAME, SPLIT_VERSION, DATE_COLUMN_NAME,
    TRAIN_END_DATE, VALIDATION_END_DATE, TEST_END_DATE,
    SPLIT_METHOD, STATUS, NOTES
) VALUES (
    s.DATASET_NAME, s.SPLIT_VERSION, s.DATE_COLUMN_NAME,
    s.TRAIN_END_DATE, s.VALIDATION_END_DATE, s.TEST_END_DATE,
    s.SPLIT_METHOD, s.STATUS, s.NOTES
);


