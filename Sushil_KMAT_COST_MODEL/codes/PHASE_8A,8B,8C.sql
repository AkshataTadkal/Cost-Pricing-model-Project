-- ============================================================
-- 4. SCORE THE CHRONOLOGICAL VALIDATION SET
-- ============================================================

CREATE OR REPLACE TABLE CSS_VALIDATION_PREDICTIONS_V2 AS
WITH scored AS (
    SELECT
        ENTITY_ID,
        TARGET_HIGH_SCRAP_FLAG,
        CSS_CLASSIFIER_V2!PREDICT(
            INPUT_DATA => OBJECT_CONSTRUCT_KEEP_NULL(
                * EXCLUDE (
                    ENTITY_ID,
                    DATA_SPLIT,
                    TARGET_HIGH_SCRAP_FLAG
                )
            ),
            CONFIG_OBJECT => {'on_error': 'ABORT'}
        ) AS PREDICTION
    FROM CSS_VALIDATION_INPUT_V2
)
SELECT
    ENTITY_ID,
    TARGET_HIGH_SCRAP_FLAG,
    GET(PREDICTION, 'class')::VARCHAR
        AS MODEL_DEFAULT_PREDICTED_CLASS,
    GET(GET(PREDICTION, 'probability'), '1')::FLOAT
        AS CSS_HIGH_SCRAP_PROBABILITY,
    ROUND(
        100 * GET(GET(PREDICTION, 'probability'), '1')::FLOAT,
        4
    ) AS CSS_SCORE,
    PREDICTION AS RAW_PREDICTION,
    CURRENT_TIMESTAMP() AS PREDICTED_AT
FROM scored;


-- Prediction parsing gate.
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(CSS_HIGH_SCRAP_PROBABILITY IS NULL) AS NULL_PROBABILITY_ROWS,
    MIN(CSS_HIGH_SCRAP_PROBABILITY) AS MIN_PROBABILITY,
    MAX(CSS_HIGH_SCRAP_PROBABILITY) AS MAX_PROBABILITY
FROM CSS_VALIDATION_PREDICTIONS_V2;


-- ============================================================
-- 5. CALCULATE VALIDATION METRICS ACROSS THRESHOLDS
-- ============================================================

CREATE OR REPLACE TABLE CSS_VALIDATION_PREDICTIONS_V2 AS
WITH scored AS (
    SELECT
        ENTITY_ID,
        TARGET_HIGH_SCRAP_FLAG,
        CSS_CLASSIFIER_V2!PREDICT(
            INPUT_DATA => OBJECT_CONSTRUCT_KEEP_NULL(
                * EXCLUDE (
                    ENTITY_ID,
                    DATA_SPLIT,
                    TARGET_HIGH_SCRAP_FLAG
                )
            ),
            CONFIG_OBJECT => {'on_error': 'ABORT'}
        ) AS PREDICTION
    FROM CSS_VALIDATION_INPUT_V2
)
SELECT
    ENTITY_ID,
    TARGET_HIGH_SCRAP_FLAG,
    GET(PREDICTION, 'class')::VARCHAR
        AS MODEL_DEFAULT_PREDICTED_CLASS,
    GET(GET(PREDICTION, 'probability'), '1')::FLOAT
        AS CSS_HIGH_SCRAP_PROBABILITY,
    ROUND(
        100 * GET(GET(PREDICTION, 'probability'), '1')::FLOAT,
        4
    ) AS CSS_SCORE,
    PREDICTION AS RAW_PREDICTION,
    CURRENT_TIMESTAMP() AS PREDICTED_AT
FROM scored;

CREATE OR REPLACE TABLE CSS_VALIDATION_THRESHOLD_METRICS_V2 AS
WITH thresholds AS (
    SELECT ROUND(0.05 + SEQ4() * 0.01, 2) AS THRESHOLD
    FROM TABLE(GENERATOR(ROWCOUNT => 91))
),
counts AS (
    SELECT
        t.THRESHOLD,
        COUNT_IF(
            p.TARGET_HIGH_SCRAP_FLAG = 1
            AND p.CSS_HIGH_SCRAP_PROBABILITY >= t.THRESHOLD
        ) AS TP,
        COUNT_IF(
            p.TARGET_HIGH_SCRAP_FLAG = 0
            AND p.CSS_HIGH_SCRAP_PROBABILITY >= t.THRESHOLD
        ) AS FP,
        COUNT_IF(
            p.TARGET_HIGH_SCRAP_FLAG = 0
            AND p.CSS_HIGH_SCRAP_PROBABILITY < t.THRESHOLD
        ) AS TN,
        COUNT_IF(
            p.TARGET_HIGH_SCRAP_FLAG = 1
            AND p.CSS_HIGH_SCRAP_PROBABILITY < t.THRESHOLD
        ) AS FN
    FROM thresholds t
    CROSS JOIN CSS_VALIDATION_PREDICTIONS_V2 p
    GROUP BY t.THRESHOLD
),
metrics AS (
    SELECT
        THRESHOLD, TP, FP, TN, FN,
        TP::FLOAT / NULLIF(TP + FP, 0) AS PRECISION,
        TP::FLOAT / NULLIF(TP + FN, 0) AS RECALL,
        TN::FLOAT / NULLIF(TN + FP, 0) AS SPECIFICITY,
        FP::FLOAT / NULLIF(FP + TN, 0) AS FALSE_POSITIVE_RATE,
        FN::FLOAT / NULLIF(TP + FN, 0) AS FALSE_NEGATIVE_RATE
    FROM counts
)
SELECT
    *,
    2 * PRECISION * RECALL
        / NULLIF(PRECISION + RECALL, 0) AS F1_SCORE,
    5 * PRECISION * RECALL
        / NULLIF(4 * PRECISION + RECALL, 0) AS F2_SCORE,
    (RECALL + SPECIFICITY) / 2 AS BALANCED_ACCURACY
FROM metrics;


-- ============================================================
-- 6. SELECT A CANDIDATE SHADOW THRESHOLD
-- ============================================================

-- This threshold is selected only for synthetic shadow evaluation.
-- It is not an approved business decision threshold.
CREATE OR REPLACE TABLE CSS_SELECTED_THRESHOLD_V2 AS
SELECT
    'CSS_CLASSIFIER_V2' AS MODEL_NAME,
    'V2' AS MODEL_VERSION,
    THRESHOLD AS CANDIDATE_THRESHOLD,
    PRECISION,
    RECALL,
    SPECIFICITY,
    FALSE_POSITIVE_RATE,
    FALSE_NEGATIVE_RATE,
    F1_SCORE,
    F2_SCORE,
    BALANCED_ACCURACY,
    IFF(
        RECALL >= 0.70 AND SPECIFICITY >= 0.60,
        'CONSTRAINED_THRESHOLD_SELECTED',
        'FALLBACK_NO_THRESHOLD_MET_CONSTRAINTS'
    ) AS SELECTION_STATUS,
    'RECALL >= 0.70 AND SPECIFICITY >= 0.60; maximize F2'
        AS SELECTION_POLICY,
    'SHADOW' AS DEPLOYMENT_MODE,
    CURRENT_TIMESTAMP() AS SELECTED_AT
FROM CSS_VALIDATION_THRESHOLD_METRICS_V2
QUALIFY ROW_NUMBER() OVER (
    ORDER BY
        IFF(RECALL >= 0.70 AND SPECIFICITY >= 0.60, 1, 0) DESC,
        F2_SCORE DESC NULLS LAST,
        BALANCED_ACCURACY DESC NULLS LAST,
        PRECISION DESC NULLS LAST
) = 1;


SELECT *
FROM CSS_SELECTED_THRESHOLD_V2;


-- ============================================================
-- 7. SCORE THE UNTOUCHED TEST SET
-- ============================================================

CREATE OR REPLACE TABLE CSS_TEST_PREDICTIONS_V2 AS
WITH scored AS (
    SELECT
        ENTITY_ID,
        TARGET_HIGH_SCRAP_FLAG,
        CSS_CLASSIFIER_V2!PREDICT(
            INPUT_DATA => OBJECT_CONSTRUCT_KEEP_NULL(
                * EXCLUDE (
                    ENTITY_ID,
                    DATA_SPLIT,
                    TARGET_HIGH_SCRAP_FLAG
                )
            ),
            CONFIG_OBJECT => {'on_error': 'ABORT'}
        ) AS PREDICTION
    FROM CSS_TEST_INPUT_V2
)
SELECT
    ENTITY_ID,
    TARGET_HIGH_SCRAP_FLAG,
    GET(PREDICTION, 'class')::VARCHAR
        AS MODEL_DEFAULT_PREDICTED_CLASS,
    GET(GET(PREDICTION, 'probability'), '1')::FLOAT
        AS CSS_HIGH_SCRAP_PROBABILITY,
    ROUND(
        100 * GET(GET(PREDICTION, 'probability'), '1')::FLOAT,
        4
    ) AS CSS_SCORE,
    PREDICTION AS RAW_PREDICTION,
    CURRENT_TIMESTAMP() AS PREDICTED_AT
FROM scored;


-- ============================================================
-- 8. FINAL TEST METRICS AT THE LOCKED VALIDATION THRESHOLD
-- ============================================================

CREATE OR REPLACE TABLE CSS_TEST_EVALUATION_V2 AS
WITH classified AS (
    SELECT
        p.*,
        t.CANDIDATE_THRESHOLD,
        IFF(
            p.CSS_HIGH_SCRAP_PROBABILITY >= t.CANDIDATE_THRESHOLD,
            1,
            0
        ) AS PREDICTED_HIGH_SCRAP_FLAG
    FROM CSS_TEST_PREDICTIONS_V2 p
    CROSS JOIN CSS_SELECTED_THRESHOLD_V2 t
),
counts AS (
    SELECT
        MAX(CANDIDATE_THRESHOLD) AS CANDIDATE_THRESHOLD,
        COUNT_IF(
            TARGET_HIGH_SCRAP_FLAG = 1
            AND PREDICTED_HIGH_SCRAP_FLAG = 1
        ) AS TP,
        COUNT_IF(
            TARGET_HIGH_SCRAP_FLAG = 0
            AND PREDICTED_HIGH_SCRAP_FLAG = 1
        ) AS FP,
        COUNT_IF(
            TARGET_HIGH_SCRAP_FLAG = 0
            AND PREDICTED_HIGH_SCRAP_FLAG = 0
        ) AS TN,
        COUNT_IF(
            TARGET_HIGH_SCRAP_FLAG = 1
            AND PREDICTED_HIGH_SCRAP_FLAG = 0
        ) AS FN
    FROM classified
),
metrics AS (
    SELECT
        CANDIDATE_THRESHOLD, TP, FP, TN, FN,
        TP::FLOAT / NULLIF(TP + FP, 0) AS PRECISION,
        TP::FLOAT / NULLIF(TP + FN, 0) AS RECALL,
        TN::FLOAT / NULLIF(TN + FP, 0) AS SPECIFICITY,
        FP::FLOAT / NULLIF(FP + TN, 0) AS FALSE_POSITIVE_RATE,
        FN::FLOAT / NULLIF(TP + FN, 0) AS FALSE_NEGATIVE_RATE,
        (TP + TN)::FLOAT / NULLIF(TP + FP + TN + FN, 0)
            AS ACCURACY
    FROM counts
)
SELECT
    'CSS_CLASSIFIER_V2' AS MODEL_NAME,
    'V2' AS MODEL_VERSION,
    'TEST' AS DATA_SPLIT,
    CANDIDATE_THRESHOLD,
    TP AS TRUE_POSITIVES,
    FP AS FALSE_POSITIVES,
    TN AS TRUE_NEGATIVES,
    FN AS FALSE_NEGATIVES,
    PRECISION,
    RECALL,
    SPECIFICITY,
    FALSE_POSITIVE_RATE,
    FALSE_NEGATIVE_RATE,
    ACCURACY,
    2 * PRECISION * RECALL
        / NULLIF(PRECISION + RECALL, 0) AS F1_SCORE,
    5 * PRECISION * RECALL
        / NULLIF(4 * PRECISION + RECALL, 0) AS F2_SCORE,
    (RECALL + SPECIFICITY) / 2 AS BALANCED_ACCURACY,
    'SHADOW' AS DEPLOYMENT_MODE,
    FALSE AS OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM metrics;


SELECT *
FROM CSS_TEST_EVALUATION_V2;

