-- ============================================================
-- PHASE 8C - CSS CLASSIFIER V2
-- Purpose:
--   Train a synthetic-data CSS classifier and evaluate it using
--   chronological TRAIN / VALIDATION / TEST partitions.
--
-- Deployment authority:
--   SHADOW ONLY. This model must not affect official cost.
--
-- Prerequisite:
