-- 9. CREATE SHADOW OUTPUT VIEW
-- ============================================================

CREATE OR REPLACE VIEW CSS_TEST_SHADOW_OUTPUT_V2 AS
SELECT
    p.ENTITY_ID,

    p.CSS_HIGH_SCRAP_PROBABILITY,
    p.CSS_SCORE,

    t.CANDIDATE_THRESHOLD,
    t.SELECTION_STATUS,
    t.SELECTION_POLICY,

    IFF(
        p.CSS_HIGH_SCRAP_PROBABILITY >= t.CANDIDATE_THRESHOLD,
        1,
        0
    ) AS PREDICTED_HIGH_SCRAP_FLAG,

    p.TARGET_HIGH_SCRAP_FLAG AS ACTUAL_HIGH_SCRAP_FLAG,

    CASE
        WHEN p.TARGET_HIGH_SCRAP_FLAG = 1
         AND p.CSS_HIGH_SCRAP_PROBABILITY >= t.CANDIDATE_THRESHOLD
            THEN 'TRUE_POSITIVE'

        WHEN p.TARGET_HIGH_SCRAP_FLAG = 0
         AND p.CSS_HIGH_SCRAP_PROBABILITY >= t.CANDIDATE_THRESHOLD
            THEN 'FALSE_POSITIVE'

        WHEN p.TARGET_HIGH_SCRAP_FLAG = 0
         AND p.CSS_HIGH_SCRAP_PROBABILITY < t.CANDIDATE_THRESHOLD
            THEN 'TRUE_NEGATIVE'

        WHEN p.TARGET_HIGH_SCRAP_FLAG = 1
         AND p.CSS_HIGH_SCRAP_PROBABILITY < t.CANDIDATE_THRESHOLD
            THEN 'FALSE_NEGATIVE'

        ELSE 'UNKNOWN'
    END AS OUTCOME_TYPE,

    'CSS_CLASSIFIER_V2' AS MODEL_NAME,
    'V2' AS MODEL_VERSION,
    'CSS_FEATURES_V2' AS FEATURE_SET_VERSION,
    'TEST' AS DATA_SPLIT,

    'SHADOW' AS DEPLOYMENT_MODE,
    FALSE AS OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    FALSE AS BUSINESS_DECISION_ALLOWED_FLAG,

    CASE
        WHEN t.SELECTION_STATUS = 'CONSTRAINED_THRESHOLD_SELECTED'
            THEN 'SHADOW_EVALUATION_READY'
        ELSE 'THRESHOLD_NOT_ACCEPTABLE'
    END AS SHADOW_STATUS,

    p.PREDICTED_AT

FROM CSS_TEST_PREDICTIONS_V2 p
CROSS JOIN CSS_SELECTED_THRESHOLD_V2 t;

