CREATE TABLE IF NOT EXISTS MODEL_REGISTRY (
    MODEL_NAME VARCHAR NOT NULL,
    MODEL_VERSION VARCHAR NOT NULL,
    MODEL_FAMILY VARCHAR NOT NULL,
    FEATURE_SET_VERSION VARCHAR NOT NULL,
    TRAINING_DATA_CLASS VARCHAR NOT NULL,
    VALIDATION_STATUS VARCHAR NOT NULL,
    DEPLOYMENT_MODE VARCHAR NOT NULL,
    OFFICIAL_COST_IMPACT_ALLOWED_FLAG BOOLEAN NOT NULL,
    BUSINESS_DECISION_ALLOWED_FLAG BOOLEAN NOT NULL,
    METRICS_JSON VARIANT,
    DECISION_REASON VARCHAR,
    MODEL_OWNER VARCHAR,
    BUSINESS_OWNER VARCHAR,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

MERGE INTO MODEL_REGISTRY target
USING (
    SELECT
        MODEL_NAME,
        MODEL_VERSION,
        'MULTI_SERIES_FORECASTING' AS MODEL_FAMILY,
        'FMIS_FEATURES_V2' AS FEATURE_SET_VERSION,
        'SYNTHETIC' AS TRAINING_DATA_CLASS,
        VALIDATION_STATUS,
        DEPLOYMENT_MODE,
        OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
        BUSINESS_DECISION_ALLOWED_FLAG,
        OBJECT_CONSTRUCT_KEEP_NULL(
            'selected_forecast_method', SELECTED_FORECAST_METHOD,
            'test_mae', SELECTED_MAE,
            'naive_mae', NAIVE_MAE,
            'test_wape', SELECTED_WAPE,
            'naive_wape', NAIVE_WAPE,
            'test_mape', SELECTED_MAPE,
            'prediction_interval_coverage', PREDICTION_INTERVAL_COVERAGE,
            'mae_improvement_vs_naive', MAE_IMPROVEMENT_VS_NAIVE,
            'invalid_multiplier_rows', INVALID_MULTIPLIER_ROWS,
            'minimum_fmis_multiplier', MIN_SELECTED_FMIS_MULTIPLIER,
            'maximum_fmis_multiplier', MAX_SELECTED_FMIS_MULTIPLIER
        ) AS METRICS_JSON,
        'Raw FMIS V2 outperformed the naive baseline and the validation-derived series fallback on the untouched synthetic test period. The model remains shadow-only and requires real historical validation before production use.' AS DECISION_REASON,
        'DATA_SCIENCE' AS MODEL_OWNER,
        'PROCUREMENT_FINANCE' AS BUSINESS_OWNER
    FROM FMIS_FINAL_TEST_EVALUATION_V2
) source
ON target.MODEL_NAME = source.MODEL_NAME
AND target.MODEL_VERSION = source.MODEL_VERSION
WHEN MATCHED THEN UPDATE SET
    MODEL_FAMILY = source.MODEL_FAMILY,
    FEATURE_SET_VERSION = source.FEATURE_SET_VERSION,
    TRAINING_DATA_CLASS = source.TRAINING_DATA_CLASS,
    VALIDATION_STATUS = source.VALIDATION_STATUS,
    DEPLOYMENT_MODE = source.DEPLOYMENT_MODE,
    OFFICIAL_COST_IMPACT_ALLOWED_FLAG = source.OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    BUSINESS_DECISION_ALLOWED_FLAG = source.BUSINESS_DECISION_ALLOWED_FLAG,
    METRICS_JSON = source.METRICS_JSON,
    DECISION_REASON = source.DECISION_REASON,
    MODEL_OWNER = source.MODEL_OWNER,
    BUSINESS_OWNER = source.BUSINESS_OWNER,
    UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    MODEL_NAME,
    MODEL_VERSION,
    MODEL_FAMILY,
    FEATURE_SET_VERSION,
    TRAINING_DATA_CLASS,
    VALIDATION_STATUS,
    DEPLOYMENT_MODE,
    OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    BUSINESS_DECISION_ALLOWED_FLAG,
    METRICS_JSON,
    DECISION_REASON,
    MODEL_OWNER,
    BUSINESS_OWNER
)
VALUES (
    source.MODEL_NAME,
    source.MODEL_VERSION,
    source.MODEL_FAMILY,
    source.FEATURE_SET_VERSION,
    source.TRAINING_DATA_CLASS,
    source.VALIDATION_STATUS,
    source.DEPLOYMENT_MODE,
    source.OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    source.BUSINESS_DECISION_ALLOWED_FLAG,
    source.METRICS_JSON,
    source.DECISION_REASON,
    source.MODEL_OWNER,
    source.BUSINESS_OWNER
);

