-- ============================================================
-- 1. CREATE LEAKAGE-SAFE TRAINING AND SCORING VIEWS
-- ============================================================

-- The training view contains only prediction-time features and the target.
-- ENTITY_ID and DATA_SPLIT are not included because Snowflake treats every
-- non-target column in INPUT_DATA as a model feature.

CREATE OR REPLACE VIEW CSS_TRAIN_INPUT_V2 AS
SELECT * EXCLUDE (ENTITY_ID, DATA_SPLIT)
FROM CSS_MODEL_DATASET_V2
WHERE DATA_SPLIT = 'TRAIN';

CREATE OR REPLACE VIEW CSS_VALIDATION_INPUT_V2 AS
SELECT *
FROM CSS_MODEL_DATASET_V2
WHERE DATA_SPLIT = 'VALIDATION';

CREATE OR REPLACE VIEW CSS_TEST_INPUT_V2 AS
SELECT *
FROM CSS_MODEL_DATASET_V2
WHERE DATA_SPLIT = 'TEST';
-- ============================================================
-- 2. PRE-TRAINING GATES
-- ============================================================

-- Gate A: training data must contain both target classes.
SELECT
    TARGET_HIGH_SCRAP_FLAG,
    COUNT(*) AS ROW_COUNT
FROM CSS_TRAIN_INPUT_V2
GROUP BY TARGET_HIGH_SCRAP_FLAG
ORDER BY TARGET_HIGH_SCRAP_FLAG;


-- Gate B: no null targets.
SELECT
    COUNT(*) AS TRAIN_ROWS,
    COUNT_IF(TARGET_HIGH_SCRAP_FLAG IS NULL) AS NULL_TARGET_ROWS,
    COUNT(DISTINCT TARGET_HIGH_SCRAP_FLAG) AS TARGET_CLASS_COUNT
FROM CSS_TRAIN_INPUT_V2;


-- Gate C: chronological datasets must not overlap.
SELECT
    (SELECT COUNT(*) FROM CSS_TRAIN_INPUT_V2) AS TRAIN_ROWS,
    (SELECT COUNT(*) FROM CSS_VALIDATION_INPUT_V2) AS VALIDATION_ROWS,
    (SELECT COUNT(*) FROM CSS_TEST_INPUT_V2) AS TEST_ROWS;


-- ============================================================
-- 3. TRAIN THE CLASSIFIER
-- ============================================================

-- Built-in evaluation is disabled because it uses an internal holdout.
-- This project uses the already-governed chronological validation/test sets.
CREATE OR REPLACE SNOWFLAKE.ML.CLASSIFICATION CSS_CLASSIFIER_V2 (
    INPUT_DATA => SYSTEM$REFERENCE(
        'VIEW',
        'KMAT_COST_MODEL_DB.CORE_ML.CSS_TRAIN_INPUT_V2'
    ),
    TARGET_COLNAME => 'TARGET_HIGH_SCRAP_FLAG',
    CONFIG_OBJECT => {
        'evaluate': FALSE,
        'on_error': 'ABORT'
    }
)
COMMENT = 'Stronger synthetic CSS classifier V2. SHADOW ONLY.';



