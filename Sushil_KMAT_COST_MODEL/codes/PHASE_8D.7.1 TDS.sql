    MODEL_NAME VARCHAR NOT NULL,
    MODEL_VERSION VARCHAR NOT NULL,
    MODEL_FAMILY VARCHAR NOT NULL,
    FEATURE_SET_VERSION VARCHAR NOT NULL,
    TRAINING_DATA_CLASS VARCHAR NOT NULL,

    VALIDATION_STATUS VARCHAR NOT NULL,
    DEPLOYMENT_MODE VARCHAR NOT NULL,

    OFFICIAL_COST_IMPACT_ALLOWED_FLAG BOOLEAN NOT NULL,
    BUSINESS_DECISION_ALLOWED_FLAG BOOLEAN NOT NULL,

    METRICS_JSON VARIANT,
    DECISION_REASON VARCHAR,

    MODEL_OWNER VARCHAR,
    BUSINESS_OWNER VARCHAR,

    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


MERGE INTO MODEL_REGISTRY target
USING (
    SELECT
        PHYSICAL_MODEL_NAME
            AS MODEL_NAME,

        PHYSICAL_MODEL_VERSION
            AS MODEL_VERSION,

        'XGBOOST_REGRESSION'
            AS MODEL_FAMILY,

        FEATURE_SET_VERSION,

        TRAINING_DATA_CLASS,
        VALIDATION_STATUS,
        DEPLOYMENT_MODE,

        OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
        BUSINESS_DECISION_ALLOWED_FLAG,

        METRICS_JSON,
        DECISION_REASON,

        'DATA_SCIENCE'
            AS MODEL_OWNER,

        'MANUFACTURING_FINANCE'
            AS BUSINESS_OWNER

    FROM TDS_MODEL_GOVERNANCE
    WHERE PHYSICAL_MODEL_NAME = 'TDS_XGB_REGRESSOR'
      AND PHYSICAL_MODEL_VERSION = 'V2_SHADOW_1'
) source

ON target.MODEL_NAME = source.MODEL_NAME
AND target.MODEL_VERSION = source.MODEL_VERSION

WHEN MATCHED THEN UPDATE SET
    MODEL_FAMILY = source.MODEL_FAMILY,
    FEATURE_SET_VERSION = source.FEATURE_SET_VERSION,
    TRAINING_DATA_CLASS = source.TRAINING_DATA_CLASS,
    VALIDATION_STATUS = source.VALIDATION_STATUS,
    DEPLOYMENT_MODE = source.DEPLOYMENT_MODE,
    OFFICIAL_COST_IMPACT_ALLOWED_FLAG =
        source.OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    BUSINESS_DECISION_ALLOWED_FLAG =
        source.BUSINESS_DECISION_ALLOWED_FLAG,
    METRICS_JSON = source.METRICS_JSON,
    DECISION_REASON = source.DECISION_REASON,
    MODEL_OWNER = source.MODEL_OWNER,
    BUSINESS_OWNER = source.BUSINESS_OWNER,
    UPDATED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    MODEL_NAME,
    MODEL_VERSION,
    MODEL_FAMILY,
    FEATURE_SET_VERSION,
    TRAINING_DATA_CLASS,

    VALIDATION_STATUS,
    DEPLOYMENT_MODE,

    OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    BUSINESS_DECISION_ALLOWED_FLAG,

    METRICS_JSON,
    DECISION_REASON,

    MODEL_OWNER,
    BUSINESS_OWNER
)
VALUES (
    source.MODEL_NAME,
    source.MODEL_VERSION,
    source.MODEL_FAMILY,
    source.FEATURE_SET_VERSION,
    source.TRAINING_DATA_CLASS,

    source.VALIDATION_STATUS,
    source.DEPLOYMENT_MODE,

    source.OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    source.BUSINESS_DECISION_ALLOWED_FLAG,

    source.METRICS_JSON,
    source.DECISION_REASON,

    source.MODEL_OWNER,
    source.BUSINESS_OWNER
);


