-- ------------------------------------------------------------
-- 1. RAW VERSUS CLIPPED RANGE DIAGNOSTICS
-- ------------------------------------------------------------

CREATE OR REPLACE TABLE TDS_PREDICTION_RANGE_DIAGNOSTICS_V2 AS
SELECT
    COUNT(*) AS OBSERVATION_COUNT,

    COUNT_IF(
        RAW_PREDICTED_TDS_FACTOR IS NULL
    ) AS NULL_RAW_PREDICTIONS,

    COUNT_IF(
        PREDICTED_TDS_FACTOR IS NULL
    ) AS NULL_SELECTED_PREDICTIONS,

    COUNT_IF(
        RAW_PREDICTED_TDS_FACTOR < 1.0
        OR RAW_PREDICTED_TDS_FACTOR > 3.5
    ) AS RAW_RANGE_VIOLATION_ROWS,

    COUNT_IF(
        ABS(
            RAW_PREDICTED_TDS_FACTOR
            - PREDICTED_TDS_FACTOR
        ) > 0.0000001
    ) AS CLIPPED_PREDICTION_ROWS,

    MIN(RAW_PREDICTED_TDS_FACTOR)
        AS RAW_PREDICTION_MIN,

    MAX(RAW_PREDICTED_TDS_FACTOR)
        AS RAW_PREDICTION_MAX,

    MIN(PREDICTED_TDS_FACTOR)
        AS SELECTED_PREDICTION_MIN,

    MAX(PREDICTED_TDS_FACTOR)
        AS SELECTED_PREDICTION_MAX,

    CURRENT_TIMESTAMP() AS CALCULATED_AT

FROM TDS_TEST_PREDICTIONS_V2;


-- ------------------------------------------------------------
-- 2. GOVERNED SHADOW OUTPUT
-- ------------------------------------------------------------

CREATE OR REPLACE VIEW TDS_SHADOW_OUTPUT_V2 AS
SELECT
    ENTITY_ID AS OPERATION_RUN_ID,
    FEATURE_AS_OF_DATE AS RUN_DATE,

    WORK_CENTER_ID,
    MACHINE_ID,
    OPERATION_ID,

    ENGINE,
    CAB,
    WHEEL,

    TARGET_TDS_FACTOR AS ACTUAL_TDS_FACTOR,

    DEVELOPMENT_RULE_BASELINE_FACTOR
        AS DETERMINISTIC_RULE_FACTOR,

    RAW_PREDICTED_TDS_FACTOR,
    PREDICTED_TDS_FACTOR
        AS RANGE_CONTROLLED_ML_FACTOR,

    CASE
        WHEN RAW_PREDICTED_TDS_FACTOR IS NULL
            THEN 'FALLBACK_NULL_PREDICTION'

        WHEN PREDICTED_TDS_FACTOR < 1.0
          OR PREDICTED_TDS_FACTOR > 3.5
            THEN 'FALLBACK_RANGE_FAILURE'

        ELSE 'ML_SHADOW_ACCEPTED'
    END AS SHADOW_SELECTION_STATUS,

    CASE
        WHEN RAW_PREDICTED_TDS_FACTOR IS NOT NULL
         AND PREDICTED_TDS_FACTOR BETWEEN 1.0 AND 3.5
            THEN PREDICTED_TDS_FACTOR

        ELSE DEVELOPMENT_RULE_BASELINE_FACTOR
    END AS SELECTED_SHADOW_TDS_FACTOR,

    ABSOLUTE_ERROR,
    UNDERPREDICTION_FLAG,
    SEVERE_UNDERPREDICTION_FLAG,
    HIGH_STRAIN_FLAG,

    'TDS_XGB_REGRESSOR'
        AS PHYSICAL_MODEL_NAME,

    'V2_SHADOW_1'
        AS PHYSICAL_MODEL_VERSION,

    MODEL_NAME
        AS EXPERIMENT_MODEL_NAME,

    MODEL_VERSION
        AS EXPERIMENT_MODEL_VERSION,

    FEATURE_SET_VERSION,

    'SYNTHETIC'
        AS TRAINING_DATA_CLASS,

    'ACCEPTED_FOR_SHADOW_WITH_MONITORING'
        AS VALIDATION_STATUS,

    'SHADOW'
        AS DEPLOYMENT_MODE,

    FALSE
        AS OFFICIAL_COST_IMPACT_ALLOWED_FLAG,

    FALSE
        AS BUSINESS_DECISION_ALLOWED_FLAG,

    CURRENT_TIMESTAMP() AS CREATED_AT

FROM TDS_TEST_PREDICTIONS_V2;


