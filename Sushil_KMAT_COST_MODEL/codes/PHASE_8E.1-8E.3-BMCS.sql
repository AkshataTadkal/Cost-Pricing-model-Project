TRUNCATE TABLE BMCS_SYNTHETIC_RAW_V2;


COPY INTO BMCS_SYNTHETIC_RAW_V2
FROM @KMAT_COST_MODEL_DB.CORE_ML.ML_SYNTHETIC_STAGE/bmcs_v2_engineer_reviewed_data.csv
FILE_FORMAT = (
    FORMAT_NAME =
        KMAT_COST_MODEL_DB.CORE_ML.PHASE8_CSV_FORMAT
)
ON_ERROR = 'ABORT_STATEMENT'
FORCE = TRUE;


-- Chronological split based only on the pre-review timestamp.
CREATE OR REPLACE VIEW BMCS_SYNTHETIC_SPLIT_V2 AS
SELECT
    raw.*,

    CASE
        WHEN FEATURE_AS_OF_TIMESTAMP
             < TO_TIMESTAMP_NTZ('2025-01-01 00:00:00')
            THEN 'TRAIN'

        WHEN FEATURE_AS_OF_TIMESTAMP
             < TO_TIMESTAMP_NTZ('2025-07-01 00:00:00')
            THEN 'VALIDATION'

        WHEN FEATURE_AS_OF_TIMESTAMP
             < TO_TIMESTAMP_NTZ('2026-01-01 00:00:00')
            THEN 'TEST'

        ELSE 'EXCLUDED'
    END AS DATA_SPLIT,

    'BMCS_SPLIT_V2' AS SPLIT_VERSION

FROM BMCS_SYNTHETIC_RAW_V2 raw;


-- Engineer-reviewed labels remain in a separate governed object.
CREATE OR REPLACE VIEW BMCS_LABEL_DATASET_V2 AS
SELECT
    RFQ_CONFIG_VERSION_ID AS ENTITY_ID,
    RFQ_ID,
    REVIEWED_AT,

    ENGINEER_FINAL_ENGINE,
    ENGINEER_FINAL_CAB,
    ENGINEER_FINAL_WHEEL,
    ENGINEER_FINAL_COLOR,

    ENGINEER_CORRECTION_COUNT,
    ENGINEER_ACCEPTED_WITHOUT_CHANGE_FLAG,
    FINAL_REVIEW_OUTCOME,
    REVIEWER_ROLE,

    CORRECT_MAPPING_FLAG AS TARGET_CORRECT_MAPPING_FLAG,

    'ENGINEER_REVIEWED_SYNTHETIC'
        AS LABEL_SOURCE,

    'BMCS_LABELS_V2'
        AS LABEL_VERSION

FROM BMCS_SYNTHETIC_SPLIT_V2;


-- Prediction-time evidence only.
