USE SCHEMA CORE_INTERNAL;

CREATE OR REPLACE PROCEDURE
    KMAT_COST_MODEL_DB.CORE_INTERNAL.RUN_KMAT_COST_SIMULATION_GOVERNED_V3(
        P_SIMULATION_ID VARCHAR
    )
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS CALLER
AS '
DECLARE
    V_PHASE10A_RESULT VARIANT;
    V_PHASE10A_STATUS VARCHAR;

    V_PHASE10B_RESULT VARIANT;
    V_PHASE10B_STATUS VARCHAR;
BEGIN
    IF (
        P_SIMULATION_ID IS NULL
        OR LENGTH(TRIM(P_SIMULATION_ID)) = 0
    ) THEN
        RETURN OBJECT_CONSTRUCT(
            ''status'', ''ERROR'',
            ''phase'', ''PHASE_10B'',
            ''message'', ''P_SIMULATION_ID is required.''
        );
    END IF;

    CALL
        KMAT_COST_MODEL_DB.CORE_INTERNAL.RUN_KMAT_COST_SIMULATION_GOVERNED_V2(
            :P_SIMULATION_ID
        )
    INTO :V_PHASE10A_RESULT;

    SELECT COALESCE(
        GET(:V_PHASE10A_RESULT, ''status'')::VARCHAR,
        ''UNKNOWN''
    )
    INTO :V_PHASE10A_STATUS;

    IF (V_PHASE10A_STATUS <> ''SUCCESS'') THEN
        RETURN OBJECT_CONSTRUCT_KEEP_NULL(
            ''status'', ''ERROR'',
            ''phase'', ''PHASE_10B'',
            ''message'',
                ''Phase 10A governed execution did not succeed.'',
            ''simulation_id'', P_SIMULATION_ID,
            ''phase10a_result'', V_PHASE10A_RESULT
        );
    END IF;

    CALL
        KMAT_COST_MODEL_DB.CORE_ML.RESOLVE_KMAT_COST_FACTOR_HIERARCHY_V1(
            :P_SIMULATION_ID
        )
    INTO :V_PHASE10B_RESULT;

    SELECT COALESCE(
        GET(:V_PHASE10B_RESULT, ''status'')::VARCHAR,
        ''UNKNOWN''
    )
    INTO :V_PHASE10B_STATUS;

    IF (V_PHASE10B_STATUS <> ''SUCCESS'') THEN
        RETURN OBJECT_CONSTRUCT_KEEP_NULL(
            ''status'', ''ERROR'',
            ''phase'', ''PHASE_10B'',
            ''message'',
                ''Fallback and approval hierarchy failed or requires cost recalculation.'',
            ''simulation_id'', P_SIMULATION_ID,
            ''phase10a_result'', V_PHASE10A_RESULT,
            ''phase10b_result'', V_PHASE10B_RESULT
        );
    END IF;

    RETURN OBJECT_CONSTRUCT_KEEP_NULL(
        ''status'', ''SUCCESS'',
        ''phase'', ''PHASE_10B'',
        ''simulation_id'', P_SIMULATION_ID,
        ''deployment_mode'', ''SHADOW'',
        ''phase10a_result'', V_PHASE10A_RESULT,
        ''phase10b_result'', V_PHASE10B_RESULT,
        ''official_cost_changed_by_phase10b'', FALSE
    );
END;
';


