CREATE OR REPLACE PROCEDURE CORE_ML.PREPARE_KMAT_GOVERNED_COST_INPUT_V2(
    P_SIMULATION_ID VARCHAR
)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    V_SUMMARY_COUNT NUMBER DEFAULT 0;

    V_KMAT_ID VARCHAR;
    V_RFQ_ID VARCHAR;
    V_COST_CALCULATED_AT TIMESTAMP_NTZ;

    V_MATERIAL_COST FLOAT;
    V_LABOR_COST FLOAT;
    V_MACHINE_COST FLOAT;
    V_OVERHEAD_COST FLOAT;
    V_TOTAL_CONFIGURED_COST FLOAT;

    V_BASELINE_TOTAL_COST FLOAT;
    V_OFFICIAL_RISK_TOTAL_COST FLOAT;
    V_OFFICIAL_FLOOR_PRICE FLOAT;
    V_OFFICIAL_TARGET_PRICE FLOAT;
    V_OFFICIAL_CEILING_PRICE FLOAT;

    V_RULE_SCRAP_RATE FLOAT;
    V_RULE_FMIS_MULTIPLIER FLOAT;
    V_RULE_TDS_FACTOR FLOAT;

    V_FINAL_TRUSTED_COST_ALLOWED BOOLEAN;
    V_QUOTE_TRUST_STATUS VARCHAR;
    V_OFFICIAL_BMCS_REVIEW_STATUS VARCHAR;

    V_ACTIVE_POLICY_COUNT NUMBER DEFAULT 0;
    V_INVALID_POLICY_COUNT NUMBER DEFAULT 0;

    V_CSS_ROW VARIANT;
    V_FMIS_ROW VARIANT;
    V_TDS_ROW VARIANT;
    V_BMCS_ROW VARIANT;

    V_CSS_DECISION_ID VARCHAR;
    V_CSS_POLICY_ID VARCHAR;
    V_CSS_POLICY_VERSION VARCHAR;
    V_CSS_MODEL_NAME VARCHAR;
    V_CSS_MODEL_VERSION VARCHAR;
    V_CSS_FEATURE_SET_VERSION VARCHAR;
    V_CSS_DEPLOYMENT_MODE VARCHAR;
    V_CSS_RAW_ML_VALUE FLOAT;
    V_CSS_RECOMMENDED_VALUE FLOAT;
    V_CSS_APPROVED_OVERRIDE FLOAT;
    V_CSS_SHADOW_VALUE FLOAT;
    V_CSS_ML_ACCEPTED BOOLEAN DEFAULT FALSE;
    V_CSS_COST_AUTHORITY BOOLEAN DEFAULT FALSE;
    V_CSS_BUSINESS_AUTHORITY BOOLEAN DEFAULT FALSE;
    V_CSS_OVERRIDE_APPLIED BOOLEAN DEFAULT FALSE;

    V_FMIS_DECISION_ID VARCHAR;
    V_FMIS_POLICY_ID VARCHAR;
    V_FMIS_POLICY_VERSION VARCHAR;
    V_FMIS_MODEL_NAME VARCHAR;
    V_FMIS_MODEL_VERSION VARCHAR;
    V_FMIS_FEATURE_SET_VERSION VARCHAR;
    V_FMIS_DEPLOYMENT_MODE VARCHAR;
    V_FMIS_RAW_ML_VALUE FLOAT;
    V_FMIS_RECOMMENDED_VALUE FLOAT;
    V_FMIS_APPROVED_OVERRIDE FLOAT;
    V_FMIS_SHADOW_VALUE FLOAT;
    V_FMIS_ML_ACCEPTED BOOLEAN DEFAULT FALSE;
    V_FMIS_COST_AUTHORITY BOOLEAN DEFAULT FALSE;
    V_FMIS_BUSINESS_AUTHORITY BOOLEAN DEFAULT FALSE;
    V_FMIS_OVERRIDE_APPLIED BOOLEAN DEFAULT FALSE;

    V_TDS_DECISION_ID VARCHAR;
    V_TDS_POLICY_ID VARCHAR;
    V_TDS_POLICY_VERSION VARCHAR;
    V_TDS_MODEL_NAME VARCHAR;
    V_TDS_MODEL_VERSION VARCHAR;
    V_TDS_FEATURE_SET_VERSION VARCHAR;
    V_TDS_DEPLOYMENT_MODE VARCHAR;
    V_TDS_RAW_ML_VALUE FLOAT;
    V_TDS_RECOMMENDED_VALUE FLOAT;
    V_TDS_APPROVED_OVERRIDE FLOAT;
    V_TDS_SHADOW_VALUE FLOAT;
    V_TDS_ML_ACCEPTED BOOLEAN DEFAULT FALSE;
    V_TDS_COST_AUTHORITY BOOLEAN DEFAULT FALSE;
    V_TDS_BUSINESS_AUTHORITY BOOLEAN DEFAULT FALSE;
    V_TDS_OVERRIDE_APPLIED BOOLEAN DEFAULT FALSE;

    V_BMCS_DECISION_ID VARCHAR;
    V_BMCS_POLICY_ID VARCHAR;
    V_BMCS_POLICY_VERSION VARCHAR;
    V_BMCS_MODEL_NAME VARCHAR;
    V_BMCS_MODEL_VERSION VARCHAR;
    V_BMCS_FEATURE_SET_VERSION VARCHAR;
    V_BMCS_DEPLOYMENT_MODE VARCHAR;
    V_BMCS_RAW_ML_VALUE FLOAT;
    V_BMCS_ML_SCORE FLOAT;
    V_BMCS_APPROVED_STATUS VARCHAR;
    V_BMCS_SHADOW_STATUS VARCHAR;
    V_BMCS_COST_AUTHORITY BOOLEAN DEFAULT FALSE;
    V_BMCS_BUSINESS_AUTHORITY BOOLEAN DEFAULT FALSE;
    V_BMCS_OVERRIDE_APPLIED BOOLEAN DEFAULT FALSE;

    V_FINAL_SCRAP_RATE FLOAT;
    V_FINAL_FMIS_MULTIPLIER FLOAT;
    V_FINAL_TDS_FACTOR FLOAT;

    V_CSS_FINAL_SOURCE VARCHAR;
    V_FMIS_FINAL_SOURCE VARCHAR;
    V_TDS_FINAL_SOURCE VARCHAR;
    V_BMCS_FINAL_SOURCE VARCHAR;

    V_COST_DECISION_COUNT NUMBER DEFAULT 0;
    V_BMCS_DECISION_COUNT NUMBER DEFAULT 0;

    V_SAFETY_GATE_PASS BOOLEAN DEFAULT FALSE;
    V_COST_ENGINE_ALLOWED BOOLEAN DEFAULT FALSE;
    V_INTEGRATION_STATUS VARCHAR;
    V_INTEGRATION_REASON VARCHAR;
    V_RETURN_STATUS VARCHAR;

    V_AUDIT_EVENT_ID VARCHAR;
    V_POLICY_AND_MODEL_SNAPSHOT VARIANT;
    V_AUDIT_SNAPSHOT VARIANT;
BEGIN
    IF (
        P_SIMULATION_ID IS NULL
        OR LENGTH(TRIM(P_SIMULATION_ID)) = 0
    ) THEN
        RETURN OBJECT_CONSTRUCT(
            ''status'', ''ERROR'',
            ''message'', ''P_SIMULATION_ID is required.''
        );
    END IF;

    SELECT COUNT(*)
    INTO :V_SUMMARY_COUNT
    FROM KMAT_COST_MODEL_DB.CORE_OUTPUT.KMAT_CONFIGURED_COST_SUMMARY
    WHERE SIMULATION_ID = :P_SIMULATION_ID;

    IF (V_SUMMARY_COUNT = 0) THEN
        RETURN OBJECT_CONSTRUCT(
            ''status'', ''ERROR'',
            ''message'',
            ''No official cost summary exists. Run the deterministic engine first.'',
            ''simulation_id'', P_SIMULATION_ID
        );
    END IF;

    SELECT
        KMAT_ID,
        RFQ_ID,
        CALCULATED_AT,

        MATERIAL_COST_USD::FLOAT,
        LABOR_COST_USD::FLOAT,
        MACHINE_COST_USD::FLOAT,
        OVERHEAD_COST_USD::FLOAT,
        TOTAL_CONFIGURED_COST_USD::FLOAT,

        BASELINE_TOTAL_COST_USD::FLOAT,
        RISK_ADJUSTED_TOTAL_COST_USD::FLOAT,
        FLOOR_PRICE_USD::FLOAT,
        TARGET_PRICE_USD::FLOAT,
        CEILING_PRICE_USD::FLOAT,

        COALESCE(
            SCRAP_RATE_APPLIED::FLOAT,
            0.0::FLOAT
        ),
        COALESCE(
            AVG_WEIGHTED_FMIS::FLOAT,
            1.0::FLOAT
        ),
        COALESCE(
            MAX_TDS_FACTOR::FLOAT,
            1.0::FLOAT
        ),

        FINAL_TRUSTED_COST_ALLOWED_FLAG,
        QUOTE_TRUST_STATUS,
        BMCS_REVIEW_STATUS
    INTO
        :V_KMAT_ID,
        :V_RFQ_ID,
        :V_COST_CALCULATED_AT,

        :V_MATERIAL_COST,
        :V_LABOR_COST,
        :V_MACHINE_COST,
        :V_OVERHEAD_COST,
        :V_TOTAL_CONFIGURED_COST,

        :V_BASELINE_TOTAL_COST,
        :V_OFFICIAL_RISK_TOTAL_COST,
        :V_OFFICIAL_FLOOR_PRICE,
        :V_OFFICIAL_TARGET_PRICE,
        :V_OFFICIAL_CEILING_PRICE,

        :V_RULE_SCRAP_RATE,
        :V_RULE_FMIS_MULTIPLIER,
        :V_RULE_TDS_FACTOR,

        :V_FINAL_TRUSTED_COST_ALLOWED,
        :V_QUOTE_TRUST_STATUS,
        :V_OFFICIAL_BMCS_REVIEW_STATUS
    FROM (
        SELECT *
        FROM KMAT_COST_MODEL_DB.CORE_OUTPUT.KMAT_CONFIGURED_COST_SUMMARY
        WHERE SIMULATION_ID = :P_SIMULATION_ID
        QUALIFY ROW_NUMBER() OVER (
            ORDER BY CALCULATED_AT DESC
        ) = 1
    );

    IF (
        V_RULE_SCRAP_RATE < 0.0
        OR V_RULE_SCRAP_RATE > 1.0
    ) THEN
        RETURN OBJECT_CONSTRUCT(
            ''status'', ''ERROR'',
            ''message'',
            ''Official SCRAP_RATE_APPLIED is outside 0 to 1.'',
            ''scrap_rate'', V_RULE_SCRAP_RATE
        );
    END IF;

    IF (V_RULE_FMIS_MULTIPLIER <= 0.0) THEN
        RETURN OBJECT_CONSTRUCT(
            ''status'', ''ERROR'',
            ''message'',
            ''Official AVG_WEIGHTED_FMIS must be greater than 0.'',
            ''fmis_multiplier'', V_RULE_FMIS_MULTIPLIER
        );
    END IF;

    IF (
        V_RULE_TDS_FACTOR < 1.0
        OR V_RULE_TDS_FACTOR > 3.5
    ) THEN
        RETURN OBJECT_CONSTRUCT(
            ''status'', ''ERROR'',
            ''message'',
            ''Official MAX_TDS_FACTOR is outside 1.0 to 3.5.'',
            ''tds_factor'', V_RULE_TDS_FACTOR
        );
    END IF;

    SELECT
        COUNT(*)::NUMBER,
        COALESCE(
            COUNT_IF(
                DEPLOYMENT_MODE <> ''SHADOW''
                OR AUTO_USE_ALLOWED_FLAG = TRUE
                OR OFFICIAL_COST_IMPACT_ALLOWED_FLAG = TRUE
                OR BUSINESS_DECISION_ALLOWED_FLAG = TRUE
                OR (
                    MODEL_DOMAIN = ''BMCS''
                    AND OFFICIAL_COST_IMPACT_ALLOWED_FLAG = TRUE
                )
            ),
            0
        )::NUMBER
    INTO
        :V_ACTIVE_POLICY_COUNT,
        :V_INVALID_POLICY_COUNT
    FROM KMAT_COST_MODEL_DB.CORE_ML.VW_ML_DECISION_POLICY_CURRENT_V1;

    IF (
        V_ACTIVE_POLICY_COUNT <> 4
        OR V_INVALID_POLICY_COUNT > 0
    ) THEN
        RETURN OBJECT_CONSTRUCT(
            ''status'', ''ERROR'',
            ''integration_status'', ''SAFETY_BLOCKED'',
            ''message'',
            ''Phase 10A requires exactly four valid SHADOW policies.'',
            ''active_policy_count'', V_ACTIVE_POLICY_COUNT,
            ''invalid_policy_count'', V_INVALID_POLICY_COUNT
        );
    END IF;

    SELECT MAX_BY(
        OBJECT_CONSTRUCT_KEEP_NULL(
            ''DECISION_ID'', DECISION_ID,
            ''POLICY_ID'', POLICY_ID,
            ''POLICY_VERSION'', POLICY_VERSION,
