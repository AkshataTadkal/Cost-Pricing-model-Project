    WHERE MODEL_DOMAIN = UPPER(TRIM(:P_MODEL_DOMAIN))
      AND DEFAULT_POLICY_VERSION = :P_DEFAULT_POLICY_VERSION
      AND POLICY_STATUS = ''DRAFT'';

    IF (V_POLICY_COUNT <> 1) THEN
        RETURN OBJECT_CONSTRUCT(
            ''status'', ''ERROR'',
            ''message'',
            ''Exactly one DRAFT safe-default policy must exist.'',
            ''policy_count'', V_POLICY_COUNT
        );
    END IF;

    SELECT
        OUTPUT_TYPE,
        DEFAULT_NUMERIC_VALUE::FLOAT,
        DEFAULT_TEXT_VALUE,
        VALID_MIN_VALUE::FLOAT,
        VALID_MAX_VALUE::FLOAT
    INTO
        :V_OUTPUT_TYPE,
        :V_NUMERIC_VALUE,
        :V_TEXT_VALUE,
        :V_MIN_VALUE,
        :V_MAX_VALUE
    FROM CORE_ML.KMAT_FACTOR_SAFE_DEFAULT_POLICY_V1
    WHERE MODEL_DOMAIN = UPPER(TRIM(:P_MODEL_DOMAIN))
      AND DEFAULT_POLICY_VERSION = :P_DEFAULT_POLICY_VERSION
      AND POLICY_STATUS = ''DRAFT'';

    IF (V_OUTPUT_TYPE = ''NUMERIC'') THEN
        IF (V_NUMERIC_VALUE IS NULL) THEN
            RETURN OBJECT_CONSTRUCT(
                ''status'', ''ERROR'',
                ''message'',
                ''Numeric safe-default policy requires DEFAULT_NUMERIC_VALUE.''
            );
        END IF;

        IF (
            V_MIN_VALUE IS NOT NULL
            AND V_NUMERIC_VALUE < V_MIN_VALUE
        ) THEN
            RETURN OBJECT_CONSTRUCT(
                ''status'', ''ERROR'',
                ''message'',
                ''Numeric safe default is below VALID_MIN_VALUE.''
            );
        END IF;

        IF (
            V_MAX_VALUE IS NOT NULL
            AND V_NUMERIC_VALUE > V_MAX_VALUE
        ) THEN
            RETURN OBJECT_CONSTRUCT(
                ''status'', ''ERROR'',
                ''message'',
                ''Numeric safe default is above VALID_MAX_VALUE.''
            );
        END IF;

    ELSEIF (V_OUTPUT_TYPE = ''TEXT'') THEN
        IF (
            V_TEXT_VALUE IS NULL
            OR LENGTH(TRIM(V_TEXT_VALUE)) = 0
        ) THEN
            RETURN OBJECT_CONSTRUCT(
                ''status'', ''ERROR'',
                ''message'',
                ''Text safe-default policy requires DEFAULT_TEXT_VALUE.''
            );
        END IF;

        IF (
            UPPER(TRIM(P_MODEL_DOMAIN)) = ''BMCS''
            AND UPPER(TRIM(V_TEXT_VALUE))
                NOT IN (
                    ''AUTO_APPROVED'',
                    ''REVIEW_RECOMMENDED'',
                    ''REVIEW_REQUIRED'',
                    ''NOT_APPLICABLE''
                )
        ) THEN
            RETURN OBJECT_CONSTRUCT(
                ''status'', ''ERROR'',
                ''message'',
                ''BMCS safe default contains an unsupported review status.''
            );
        END IF;

    ELSE
        RETURN OBJECT_CONSTRUCT(
            ''status'', ''ERROR'',
            ''message'',
            ''OUTPUT_TYPE must be NUMERIC or TEXT.''
        );
    END IF;

    UPDATE CORE_ML.KMAT_FACTOR_SAFE_DEFAULT_POLICY_V1
    SET
        POLICY_STATUS = ''RETIRED'',
        EFFECTIVE_TO = CURRENT_TIMESTAMP(),
        UPDATED_BY = TRIM(:P_APPROVED_BY),
        UPDATED_AT = CURRENT_TIMESTAMP()
    WHERE MODEL_DOMAIN = UPPER(TRIM(:P_MODEL_DOMAIN))
      AND POLICY_STATUS = ''ACTIVE'';

    UPDATE CORE_ML.KMAT_FACTOR_SAFE_DEFAULT_POLICY_V1
    SET
        POLICY_STATUS = ''ACTIVE'',
        EFFECTIVE_FROM = CURRENT_TIMESTAMP(),
        EFFECTIVE_TO = NULL,
        APPROVED_BY = TRIM(:P_APPROVED_BY),
        APPROVED_AT = CURRENT_TIMESTAMP(),
        UPDATED_BY = TRIM(:P_APPROVED_BY),
        UPDATED_AT = CURRENT_TIMESTAMP()
    WHERE MODEL_DOMAIN = UPPER(TRIM(:P_MODEL_DOMAIN))
      AND DEFAULT_POLICY_VERSION = :P_DEFAULT_POLICY_VERSION
      AND POLICY_STATUS = ''DRAFT'';

    RETURN OBJECT_CONSTRUCT(
        ''status'', ''SUCCESS'',
        ''model_domain'', UPPER(TRIM(P_MODEL_DOMAIN)),
        ''default_policy_version'', P_DEFAULT_POLICY_VERSION,
        ''approved_by'', P_APPROVED_BY
    );
END;
';


