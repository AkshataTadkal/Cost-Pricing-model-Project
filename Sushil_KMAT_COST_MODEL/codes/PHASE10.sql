CREATE OR REPLACE PROCEDURE CORE_INTERNAL.RUN_KMAT_COST_SIMULATION_GOVERNED_V2(
    P_SIMULATION_ID VARCHAR
)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS CALLER
AS '
DECLARE
    V_ENGINE_RESULT VARCHAR;
    V_ENGINE_RESULT_JSON VARIANT;
    V_ENGINE_STATUS VARCHAR;

    V_GOVERNANCE_RESULT VARIANT;
    V_GOVERNANCE_STATUS VARCHAR;
BEGIN
    IF (
        P_SIMULATION_ID IS NULL
        OR LENGTH(TRIM(P_SIMULATION_ID)) = 0
    ) THEN
        RETURN OBJECT_CONSTRUCT(
            ''status'', ''ERROR'',
            ''message'', ''P_SIMULATION_ID is required.''
        );
    END IF;

    CALL KMAT_COST_MODEL_DB.CORE_INTERNAL.RUN_KMAT_COST_SIMULATION(
        :P_SIMULATION_ID
    ) INTO :V_ENGINE_RESULT;

    V_ENGINE_RESULT_JSON :=
        TRY_PARSE_JSON(V_ENGINE_RESULT);

    SELECT COALESCE(
        GET(:V_ENGINE_RESULT_JSON, ''status'')::VARCHAR,
        ''UNKNOWN''
    )
    INTO :V_ENGINE_STATUS;

    IF (V_ENGINE_STATUS <> ''SUCCESS'') THEN
        RETURN OBJECT_CONSTRUCT_KEEP_NULL(
            ''status'', ''ERROR'',
            ''phase'', ''PHASE_10A'',
            ''message'',
                ''The existing deterministic cost engine did not return SUCCESS.'',
            ''simulation_id'', P_SIMULATION_ID,
            ''deterministic_engine_result'',
                V_ENGINE_RESULT_JSON
        );
    END IF;

    CALL KMAT_COST_MODEL_DB.CORE_ML.PREPARE_KMAT_GOVERNED_COST_INPUT_V2(
        :P_SIMULATION_ID
    ) INTO :V_GOVERNANCE_RESULT;

    SELECT COALESCE(
        GET(:V_GOVERNANCE_RESULT, ''status'')::VARCHAR,
        ''UNKNOWN''
    )
    INTO :V_GOVERNANCE_STATUS;

    IF (V_GOVERNANCE_STATUS <> ''SUCCESS'') THEN
        RETURN OBJECT_CONSTRUCT_KEEP_NULL(
            ''status'', ''ERROR'',
            ''phase'', ''PHASE_10A'',
            ''message'',
                ''The deterministic engine succeeded but governed cost-input preparation failed or was safety-blocked.'',
            ''simulation_id'', P_SIMULATION_ID,
            ''deterministic_engine_result'',
                V_ENGINE_RESULT_JSON,
            ''governance_result'',
                V_GOVERNANCE_RESULT
        );
    END IF;

    RETURN OBJECT_CONSTRUCT_KEEP_NULL(
        ''status'', ''SUCCESS'',
        ''phase'', ''PHASE_10A'',
        ''simulation_id'', P_SIMULATION_ID,
        ''deployment_mode'', ''SHADOW'',
        ''deterministic_engine_result'',
            V_ENGINE_RESULT_JSON,
        ''governance_result'',
            V_GOVERNANCE_RESULT,
        ''official_cost_changed_by_ml'', FALSE,
        ''ml_cost_value_used'', FALSE,
        ''bmcs_direct_cost_impact_allowed'', FALSE
    );
END;
';


