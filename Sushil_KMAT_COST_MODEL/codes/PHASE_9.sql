CREATE OR REPLACE VIEW VW_ML_DECISION_POLICY_CURRENT_V1 AS
SELECT *
FROM ML_DECISION_POLICY_V1
WHERE POLICY_STATUS = 'ACTIVE'
  AND EFFECTIVE_FROM <= CURRENT_TIMESTAMP()
  AND (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO > CURRENT_TIMESTAMP())
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY MODEL_DOMAIN
    ORDER BY EFFECTIVE_FROM DESC, CREATED_AT DESC
) = 1;

CREATE OR REPLACE PROCEDURE ACTIVATE_ML_DECISION_POLICY_V1(
    P_MODEL_DOMAIN VARCHAR,
    P_POLICY_VERSION VARCHAR,
    P_APPROVED_BY VARCHAR
)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    V_POLICY_COUNT NUMBER DEFAULT 0;
    V_DEPLOYMENT_MODE VARCHAR;
    V_AUTO_USE_ALLOWED BOOLEAN;
    V_COST_IMPACT_ALLOWED BOOLEAN;
    V_BUSINESS_DECISION_ALLOWED BOOLEAN;
BEGIN
    IF (P_MODEL_DOMAIN IS NULL OR LENGTH(TRIM(P_MODEL_DOMAIN)) = 0) THEN
        RETURN OBJECT_CONSTRUCT(''status'',''ERROR'',''message'',''P_MODEL_DOMAIN is required.'');
    END IF;

    IF (P_POLICY_VERSION IS NULL OR LENGTH(TRIM(P_POLICY_VERSION)) = 0) THEN
        RETURN OBJECT_CONSTRUCT(''status'',''ERROR'',''message'',''P_POLICY_VERSION is required.'');
    END IF;

    IF (P_APPROVED_BY IS NULL OR LENGTH(TRIM(P_APPROVED_BY)) = 0) THEN
        RETURN OBJECT_CONSTRUCT(''status'',''ERROR'',''message'',''P_APPROVED_BY is required.'');
    END IF;

    SELECT COUNT(*), MAX(DEPLOYMENT_MODE), MAX(AUTO_USE_ALLOWED_FLAG),
           MAX(OFFICIAL_COST_IMPACT_ALLOWED_FLAG), MAX(BUSINESS_DECISION_ALLOWED_FLAG)
    INTO :V_POLICY_COUNT, :V_DEPLOYMENT_MODE, :V_AUTO_USE_ALLOWED,
         :V_COST_IMPACT_ALLOWED, :V_BUSINESS_DECISION_ALLOWED
    FROM ML_DECISION_POLICY_V1
    WHERE MODEL_DOMAIN = UPPER(:P_MODEL_DOMAIN)
      AND POLICY_VERSION = :P_POLICY_VERSION
      AND POLICY_STATUS = ''DRAFT'';

    IF (V_POLICY_COUNT <> 1) THEN
        RETURN OBJECT_CONSTRUCT(''status'',''ERROR'',''message'',''Exactly one DRAFT policy must exist.'');
    END IF;

    IF (V_DEPLOYMENT_MODE = ''SHADOW'' AND
        (V_AUTO_USE_ALLOWED OR V_COST_IMPACT_ALLOWED OR V_BUSINESS_DECISION_ALLOWED)) THEN
        RETURN OBJECT_CONSTRUCT(''status'',''ERROR'',''message'',''SHADOW policies cannot allow automatic use, cost impact, or business decisions.'');
    END IF;

    IF (UPPER(P_MODEL_DOMAIN) = ''BMCS'' AND V_COST_IMPACT_ALLOWED) THEN
        RETURN OBJECT_CONSTRUCT(''status'',''ERROR'',''message'',''BMCS can never directly affect cost.'');
    END IF;

    IF (V_AUTO_USE_ALLOWED AND NOT V_BUSINESS_DECISION_ALLOWED) THEN
        RETURN OBJECT_CONSTRUCT(''status'',''ERROR'',''message'',''Automatic use requires business-decision permission.'');
    END IF;

    UPDATE ML_DECISION_POLICY_V1
    SET POLICY_STATUS = ''RETIRED'', EFFECTIVE_TO = CURRENT_TIMESTAMP(), UPDATED_AT = CURRENT_TIMESTAMP()
    WHERE MODEL_DOMAIN = UPPER(:P_MODEL_DOMAIN)
      AND POLICY_STATUS = ''ACTIVE'';

    UPDATE ML_DECISION_POLICY_V1
    SET POLICY_STATUS = ''ACTIVE'', EFFECTIVE_FROM = CURRENT_TIMESTAMP(), EFFECTIVE_TO = NULL,
        APPROVED_BY = :P_APPROVED_BY, APPROVED_AT = CURRENT_TIMESTAMP(), UPDATED_AT = CURRENT_TIMESTAMP()
    WHERE MODEL_DOMAIN = UPPER(:P_MODEL_DOMAIN)
      AND POLICY_VERSION = :P_POLICY_VERSION
      AND POLICY_STATUS = ''DRAFT'';

    RETURN OBJECT_CONSTRUCT(
        ''status'',''SUCCESS'',
        ''model_domain'',UPPER(P_MODEL_DOMAIN),
        ''policy_version'',P_POLICY_VERSION,
        ''deployment_mode'',V_DEPLOYMENT_MODE,
        ''approved_by'',P_APPROVED_BY
    );
END;
';

SELECT * FROM VW_ML_DECISION_POLICY_CURRENT_V1 ORDER BY MODEL_DOMAIN;

SELECT
    MODEL_DOMAIN,
    POLICY_VERSION,
    POLICY_STATUS,
    DEPLOYMENT_MODE,
    DECISION_TYPE,
    RAW_ML_OUTPUT_NAME,
    FINAL_OUTPUT_NAME,
    FALLBACK_SOURCE,
    QUALITY_PASS_REQUIRED_FLAG,
    OOD_USE_ALLOWED_FLAG,
    AUTO_USE_ALLOWED_FLAG,
    OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    BUSINESS_DECISION_ALLOWED_FLAG,
    POLICY_CONFIG
FROM VW_ML_DECISION_POLICY_CURRENT_V1
ORDER BY MODEL_DOMAIN;

SELECT
    MODEL_DOMAIN,
    COUNT_IF(POLICY_STATUS = 'ACTIVE') AS ACTIVE_POLICY_COUNT
FROM ML_DECISION_POLICY_V1
GROUP BY MODEL_DOMAIN
HAVING COUNT_IF(POLICY_STATUS = 'ACTIVE') <> 1;

SELECT
    COUNT_IF(
        DEPLOYMENT_MODE = 'SHADOW'
        AND (
            AUTO_USE_ALLOWED_FLAG = TRUE
            OR OFFICIAL_COST_IMPACT_ALLOWED_FLAG = TRUE
            OR BUSINESS_DECISION_ALLOWED_FLAG = TRUE
        )
    ) AS INVALID_SHADOW_POLICY_ROWS,
    COUNT_IF(
        MODEL_DOMAIN = 'BMCS'
        AND OFFICIAL_COST_IMPACT_ALLOWED_FLAG = TRUE
    ) AS INVALID_BMCS_COST_POLICY_ROWS
FROM ML_DECISION_POLICY_V1
WHERE POLICY_STATUS = 'ACTIVE';

