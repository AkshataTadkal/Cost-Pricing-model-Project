        IFF(
            override_record.OVERRIDE_STATUS =
                'APPROVED_NOT_APPLIED',
            override_record.OVERRIDE_NUMERIC_VALUE,
            NULL::FLOAT
        )::FLOAT,
        decision.FINAL_NUMERIC_VALUE::FLOAT
    ) AS SHADOW_COMPARISON_NUMERIC_VALUE,

