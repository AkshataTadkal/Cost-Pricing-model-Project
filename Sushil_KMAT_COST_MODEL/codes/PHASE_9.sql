LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    V_OVERRIDE_COUNT NUMBER DEFAULT 0;
    V_DECISION_COUNT NUMBER DEFAULT 0;
    V_PENDING_COUNT NUMBER DEFAULT 0;

    V_ENTITY_ID VARCHAR;
    V_RFQ_ID VARCHAR;
    V_SIMULATION_ID VARCHAR;
    V_MODEL_DOMAIN VARCHAR;

    V_POLICY_ID VARCHAR;
    V_POLICY_VERSION VARCHAR;
    V_DEPLOYMENT_MODE VARCHAR;

