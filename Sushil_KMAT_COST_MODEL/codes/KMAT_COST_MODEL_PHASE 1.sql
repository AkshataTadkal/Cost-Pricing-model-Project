--RULE EVALUATION
WITH RULE_EVALUATION AS (
    SELECT
        h.SIMULATION_ID,
        bom.KMAT_ID,
        bom.COMPONENT_ID,
        bom.COMPONENT_DESCRIPTION,
        bom.QUANTITY,
        bom.UOM,
        bom.RULE_ID,
        bom.IS_BULK_MATERIAL,
        bom.COST_COMPONENT_GROUP,
        COALESCE(mc.STANDARD_COST_USD, 0) AS STANDARD_COST_USD,
        bom.QUANTITY * COALESCE(mc.STANDARD_COST_USD, 0) AS LINE_MATERIAL_COST_USD,
        IFF(mc.ITEM_ID IS NULL OR mc.STANDARD_COST_USD IS NULL, TRUE, FALSE) AS COST_MISSING_FLAG,
        CASE
            WHEN dr.RULE_JSON:type::STRING = 'DEFAULT'
                THEN TRUE
            WHEN cv.SELECTED_VALUE = dr.RULE_JSON:value::STRING
                THEN TRUE
            ELSE FALSE
        END AS IS_SELECTED
    FROM CORE_INPUT.SIMULATION_HEADER h
    JOIN CORE_INPUT.KMAT_SUPER_BOM bom
        ON h.KMAT_ID = bom.KMAT_ID
    JOIN CORE_INPUT.DEPENDENCY_RULES dr
        ON bom.RULE_ID = dr.RULE_ID
    LEFT JOIN CORE_INPUT.CHARACTERISTIC_VALUES cv
        ON cv.SIMULATION_ID = h.SIMULATION_ID
       AND cv.KMAT_ID = bom.KMAT_ID
       AND cv.CHARACTERISTIC_NAME = dr.RULE_JSON:characteristic::STRING
    LEFT JOIN CORE_INPUT.MATERIAL_COSTS mc
        ON bom.COMPONENT_ID = mc.ITEM_ID
    WHERE h.SIMULATION_ID = 'SIM_001'
)
SELECT
    SIMULATION_ID,
    KMAT_ID,
    COMPONENT_ID,
    COMPONENT_DESCRIPTION,
    QUANTITY,
    UOM,
    RULE_ID,
    IS_BULK_MATERIAL,
    COST_COMPONENT_GROUP,
    STANDARD_COST_USD,
    LINE_MATERIAL_COST_USD,
    COST_MISSING_FLAG
FROM RULE_EVALUATION
WHERE IS_SELECTED = TRUE
ORDER BY COST_COMPONENT_GROUP, COMPONENT_ID;

--VALIDATE MATERIAL COST
WITH RULE_EVALUATION AS (
    SELECT
        h.SIMULATION_ID,
        bom.KMAT_ID,
        bom.COMPONENT_ID,
        bom.QUANTITY,
        COALESCE(mc.STANDARD_COST_USD, 0) AS STANDARD_COST_USD,
        bom.QUANTITY * COALESCE(mc.STANDARD_COST_USD, 0) AS LINE_MATERIAL_COST_USD,
        CASE
            WHEN dr.RULE_JSON:type::STRING = 'DEFAULT'
                THEN TRUE
            WHEN cv.SELECTED_VALUE = dr.RULE_JSON:value::STRING
                THEN TRUE
            ELSE FALSE
        END AS IS_SELECTED
    FROM CORE_INPUT.SIMULATION_HEADER h
    JOIN CORE_INPUT.KMAT_SUPER_BOM bom
        ON h.KMAT_ID = bom.KMAT_ID
    JOIN CORE_INPUT.DEPENDENCY_RULES dr
        ON bom.RULE_ID = dr.RULE_ID
    LEFT JOIN CORE_INPUT.CHARACTERISTIC_VALUES cv
        ON cv.SIMULATION_ID = h.SIMULATION_ID
       AND cv.KMAT_ID = bom.KMAT_ID
       AND cv.CHARACTERISTIC_NAME = dr.RULE_JSON:characteristic::STRING
    LEFT JOIN CORE_INPUT.MATERIAL_COSTS mc
        ON bom.COMPONENT_ID = mc.ITEM_ID
    WHERE h.SIMULATION_ID = 'SIM_001'
)
SELECT
    SIMULATION_ID,
    KMAT_ID,
    SUM(LINE_MATERIAL_COST_USD) AS TOTAL_MATERIAL_COST_USD
FROM RULE_EVALUATION
WHERE IS_SELECTED = TRUE
GROUP BY SIMULATION_ID, KMAT_ID;

---VALIDATING SELECTED ROUTING OPERATIONS
WITH ROUTING_RULE_EVALUATION AS (
    SELECT
        h.SIMULATION_ID,
        rt.KMAT_ID,
        rt.OPERATION_ID,
        rt.OPERATION_DESCRIPTION,
        rt.WORK_CENTER_ID,
        rt.LABOR_HOURS,
        rt.MACHINE_HOURS,
