        rt.MACHINE_HOURS * wr.MACHINE_RATE_USD_PER_HOUR AS MACHINE_COST_USD,
        rt.RULE_ID,
        CASE
            WHEN dr.RULE_JSON:type::STRING = 'DEFAULT'
                THEN TRUE
            WHEN cv.SELECTED_VALUE = dr.RULE_JSON:value::STRING
                THEN TRUE
            ELSE FALSE
        END AS IS_SELECTED
    FROM CORE_INPUT.SIMULATION_HEADER h
    JOIN CORE_INPUT.KMAT_SUPER_ROUTING rt
        ON h.KMAT_ID = rt.KMAT_ID
    JOIN CORE_INPUT.DEPENDENCY_RULES dr
        ON rt.RULE_ID = dr.RULE_ID
    LEFT JOIN CORE_INPUT.CHARACTERISTIC_VALUES cv
        ON cv.SIMULATION_ID = h.SIMULATION_ID
       AND cv.KMAT_ID = rt.KMAT_ID
       AND cv.CHARACTERISTIC_NAME = dr.RULE_JSON:characteristic::STRING
    JOIN CORE_INPUT.WORK_CENTER_RATES wr
        ON rt.WORK_CENTER_ID = wr.WORK_CENTER_ID
    WHERE h.SIMULATION_ID = 'SIM_001'
)
SELECT
    SIMULATION_ID,
    KMAT_ID,
    OPERATION_ID,
    OPERATION_DESCRIPTION,
    WORK_CENTER_ID,
    LABOR_HOURS,
    MACHINE_HOURS,
    LABOR_COST_USD,
    MACHINE_COST_USD,
    RULE_ID
FROM ROUTING_RULE_EVALUATION
WHERE IS_SELECTED = TRUE
ORDER BY OPERATION_ID;

