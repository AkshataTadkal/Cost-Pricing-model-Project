--VALIDATE OVERHEAD RULES
WITH MATERIAL_TOTAL AS (
    SELECT
        h.SIMULATION_ID,
        bom.KMAT_ID,
        SUM(bom.QUANTITY * COALESCE(mc.STANDARD_COST_USD, 0)) AS MATERIAL_COST_USD
    FROM CORE_INPUT.SIMULATION_HEADER h
    JOIN CORE_INPUT.KMAT_SUPER_BOM bom
        ON h.KMAT_ID = bom.KMAT_ID
    JOIN CORE_INPUT.DEPENDENCY_RULES dr
        ON bom.RULE_ID = dr.RULE_ID
    LEFT JOIN CORE_INPUT.CHARACTERISTIC_VALUES cv
        ON cv.SIMULATION_ID = h.SIMULATION_ID
       AND cv.KMAT_ID = bom.KMAT_ID
       AND cv.CHARACTERISTIC_NAME = dr.RULE_JSON:characteristic::STRING
    LEFT JOIN CORE_INPUT.MATERIAL_COSTS mc
        ON bom.COMPONENT_ID = mc.ITEM_ID
    WHERE h.SIMULATION_ID = 'SIM_001'
      AND (
            dr.RULE_JSON:type::STRING = 'DEFAULT'
            OR cv.SELECTED_VALUE = dr.RULE_JSON:value::STRING
          )
    GROUP BY h.SIMULATION_ID, bom.KMAT_ID
),
OVERHEAD_RULE_EVALUATION AS (
    SELECT
        h.SIMULATION_ID,
        oh.KMAT_ID,
        oh.OVERHEAD_ID,
        oh.OVERHEAD_DESCRIPTION,
        oh.BASIS,
        oh.RATE_VALUE,
        CASE
            WHEN oh.BASIS = 'MATERIAL_PERCENT'
                THEN mt.MATERIAL_COST_USD * oh.RATE_VALUE
            WHEN oh.BASIS = 'FIXED'
                THEN oh.RATE_VALUE
            ELSE 0
        END AS OVERHEAD_COST_USD,
        CASE
            WHEN dr.RULE_JSON:type::STRING = 'DEFAULT'
                THEN TRUE
            WHEN cv.SELECTED_VALUE = dr.RULE_JSON:value::STRING
                THEN TRUE
            ELSE FALSE
        END AS IS_SELECTED
    FROM CORE_INPUT.SIMULATION_HEADER h
    JOIN CORE_INPUT.OVERHEAD_RATES oh
        ON h.KMAT_ID = oh.KMAT_ID
    JOIN CORE_INPUT.DEPENDENCY_RULES dr
        ON oh.RULE_ID = dr.RULE_ID
    LEFT JOIN CORE_INPUT.CHARACTERISTIC_VALUES cv
        ON cv.SIMULATION_ID = h.SIMULATION_ID
       AND cv.KMAT_ID = oh.KMAT_ID
       AND cv.CHARACTERISTIC_NAME = dr.RULE_JSON:characteristic::STRING
    JOIN MATERIAL_TOTAL mt
        ON h.SIMULATION_ID = mt.SIMULATION_ID
       AND h.KMAT_ID = mt.KMAT_ID
    WHERE h.SIMULATION_ID = 'SIM_001'
)
SELECT
    SIMULATION_ID,
    KMAT_ID,
    OVERHEAD_ID,
    OVERHEAD_DESCRIPTION,
    BASIS,
    RATE_VALUE,
    OVERHEAD_COST_USD
FROM OVERHEAD_RULE_EVALUATION
WHERE IS_SELECTED = TRUE
ORDER BY OVERHEAD_ID;



