    coverage.TOTAL_TEST_ROWS,
    coverage.FALLBACK_ROW_COUNT,
    evaluation.CORRECT_MAPPING_RATE,
    evaluation.ROC_AUC,
    evaluation.PR_AUC,
    evaluation.BRIER_SCORE,
    evaluation.LOG_LOSS,
    evaluation.ECE_10_BIN,
    evaluation.ACCURACY_AT_050,
    evaluation.PRECISION_AT_050,
    evaluation.RECALL_AT_050,
    evaluation.F1_AT_050,
    evaluation.RULE_BASELINE_PR_AUC,
    evaluation.RULE_BASELINE_BRIER_SCORE,
    evaluation.HYBRID_BASELINE_PR_AUC,
    evaluation.HYBRID_BASELINE_BRIER_SCORE,
    evaluation.PR_AUC_IMPROVEMENT_VS_HYBRID,
    evaluation.BRIER_IMPROVEMENT_VS_HYBRID,
    evaluation.LOW_THRESHOLD,
    evaluation.HIGH_THRESHOLD,
    evaluation.AUTO_APPROVAL_ROWS,
    evaluation.AUTO_APPROVAL_RATE,
    evaluation.INCORRECT_AUTO_APPROVAL_ROWS,
    evaluation.INCORRECT_AUTO_APPROVAL_RATE,
    evaluation.AUTO_REJECTION_ROWS,
    evaluation.AUTO_REJECTION_RATE,
    evaluation.CORRECT_MAPPING_REJECTION_ROWS,
    evaluation.CORRECT_MAPPING_REJECTION_RATE,
    evaluation.ENGINEERING_REVIEW_ROWS,
    evaluation.ENGINEERING_REVIEW_RATE,
    'ACCEPTED_FOR_SHADOW_PROBABILITY_SCORING'
        AS MODEL_PROBABILITY_STATUS,
    'REJECTED_ON_TEST'
        AS AUTOMATION_POLICY_STATUS,
    'ACCEPTED_FOR_SHADOW_WITH_REVIEW_ONLY'
        AS FINAL_VALIDATION_STATUS,
    'The probability model materially outperformed the Phase 7 development hybrid benchmark. Locked automation thresholds did not meet the approved error constraints; therefore all BMCS ML outputs remain advisory and every RFQ remains subject to governed review.'
        AS DECISION_REASON,
    'SYNTHETIC' AS TRAINING_DATA_CLASS,
    'SHADOW' AS DEPLOYMENT_MODE,
    FALSE AS OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    FALSE AS BUSINESS_DECISION_ALLOWED_FLAG,
    CURRENT_TIMESTAMP() AS FINALIZED_AT
FROM BMCS_TEST_EVALUATION_V2 evaluation
CROSS JOIN (
    SELECT
        COUNT(*) AS TOTAL_TEST_ROWS,
        COUNT_IF(
            ML_SCORING_COMPLETED_FLAG = FALSE
        ) AS FALLBACK_ROW_COUNT
    FROM BMCS_FINAL_TEST_SHADOW_OUTPUT_V2
) coverage;

CREATE TABLE IF NOT EXISTS BMCS_MODEL_GOVERNANCE (
    EXPERIMENT_MODEL_NAME VARCHAR NOT NULL,
    EXPERIMENT_MODEL_VERSION VARCHAR NOT NULL,
    FEATURE_SET_VERSION VARCHAR NOT NULL,
    CALIBRATION_METHOD VARCHAR NOT NULL,
    TRAINING_DATA_CLASS VARCHAR NOT NULL,
    MODEL_PROBABILITY_STATUS VARCHAR NOT NULL,
    AUTOMATION_POLICY_STATUS VARCHAR NOT NULL,
    DEPLOYMENT_MODE VARCHAR NOT NULL,
    ML_ADVISORY_ONLY_FLAG BOOLEAN NOT NULL,
    OFFICIAL_COST_IMPACT_ALLOWED_FLAG BOOLEAN NOT NULL,
    BUSINESS_DECISION_ALLOWED_FLAG BOOLEAN NOT NULL,
    METRICS_JSON VARIANT,
    DECISION_REASON VARCHAR,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

MERGE INTO BMCS_MODEL_GOVERNANCE target
USING (
    SELECT
        MODEL_NAME AS EXPERIMENT_MODEL_NAME,
        MODEL_VERSION AS EXPERIMENT_MODEL_VERSION,
        'BMCS_FEATURES_V2' AS FEATURE_SET_VERSION,
        CALIBRATION_METHOD,
        TRAINING_DATA_CLASS,
        MODEL_PROBABILITY_STATUS,
        AUTOMATION_POLICY_STATUS,
        DEPLOYMENT_MODE,
        TRUE AS ML_ADVISORY_ONLY_FLAG,
        OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
        BUSINESS_DECISION_ALLOWED_FLAG,
        OBJECT_CONSTRUCT_KEEP_NULL(
            'ml_scored_rows', ML_SCORED_ROW_COUNT,
            'total_test_rows', TOTAL_TEST_ROWS,
            'fallback_rows', FALLBACK_ROW_COUNT,
            'roc_auc', ROC_AUC,
            'pr_auc', PR_AUC,
            'brier_score', BRIER_SCORE,
            'log_loss', LOG_LOSS,
            'ece_10_bin', ECE_10_BIN,
            'f1_at_050', F1_AT_050,
            'hybrid_baseline_pr_auc',
                HYBRID_BASELINE_PR_AUC,
            'hybrid_baseline_brier_score',
                HYBRID_BASELINE_BRIER_SCORE,
            'pr_auc_improvement_vs_hybrid',
                PR_AUC_IMPROVEMENT_VS_HYBRID,
            'brier_improvement_vs_hybrid',
                BRIER_IMPROVEMENT_VS_HYBRID,
            'locked_low_threshold',
                LOW_THRESHOLD,
            'locked_high_threshold',
                HIGH_THRESHOLD,
            'incorrect_auto_approval_rate',
                INCORRECT_AUTO_APPROVAL_RATE,
            'correct_mapping_rejection_rate',
                CORRECT_MAPPING_REJECTION_RATE
        ) AS METRICS_JSON,
        DECISION_REASON
    FROM BMCS_FINAL_TEST_EVALUATION_V2
) source
ON target.EXPERIMENT_MODEL_NAME =
    source.EXPERIMENT_MODEL_NAME
AND target.EXPERIMENT_MODEL_VERSION =
    source.EXPERIMENT_MODEL_VERSION
WHEN MATCHED THEN UPDATE SET
    FEATURE_SET_VERSION =
        source.FEATURE_SET_VERSION,
    CALIBRATION_METHOD =
        source.CALIBRATION_METHOD,
    TRAINING_DATA_CLASS =
        source.TRAINING_DATA_CLASS,
    MODEL_PROBABILITY_STATUS =
        source.MODEL_PROBABILITY_STATUS,
    AUTOMATION_POLICY_STATUS =
        source.AUTOMATION_POLICY_STATUS,
    DEPLOYMENT_MODE =
        source.DEPLOYMENT_MODE,
    ML_ADVISORY_ONLY_FLAG =
        source.ML_ADVISORY_ONLY_FLAG,
    OFFICIAL_COST_IMPACT_ALLOWED_FLAG =
        source.OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    BUSINESS_DECISION_ALLOWED_FLAG =
        source.BUSINESS_DECISION_ALLOWED_FLAG,
    METRICS_JSON =
        source.METRICS_JSON,
    DECISION_REASON =
        source.DECISION_REASON,
    UPDATED_AT =
        CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    EXPERIMENT_MODEL_NAME,
    EXPERIMENT_MODEL_VERSION,
    FEATURE_SET_VERSION,
    CALIBRATION_METHOD,
    TRAINING_DATA_CLASS,
    MODEL_PROBABILITY_STATUS,
    AUTOMATION_POLICY_STATUS,
    DEPLOYMENT_MODE,
    ML_ADVISORY_ONLY_FLAG,
    OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    BUSINESS_DECISION_ALLOWED_FLAG,
    METRICS_JSON,
    DECISION_REASON
)
VALUES (
    source.EXPERIMENT_MODEL_NAME,
    source.EXPERIMENT_MODEL_VERSION,
    source.FEATURE_SET_VERSION,
    source.CALIBRATION_METHOD,
    source.TRAINING_DATA_CLASS,
    source.MODEL_PROBABILITY_STATUS,
    source.AUTOMATION_POLICY_STATUS,
    source.DEPLOYMENT_MODE,
    source.ML_ADVISORY_ONLY_FLAG,
    source.OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    source.BUSINESS_DECISION_ALLOWED_FLAG,
    source.METRICS_JSON,
    source.DECISION_REASON
);

