CREATE OR REPLACE TABLE KMAT_COST_MODEL_DB.CORE_ML.BMCS_THRESHOLD_POLICY_DECISION_V2 AS
SELECT
    MODEL_NAME,
    MODEL_VERSION,
    CALIBRATION_METHOD,
    LOW_THRESHOLD,
    HIGH_THRESHOLD,
    0.02 AS APPROVED_AUTO_APPROVAL_ERROR_LIMIT,
    INCORRECT_AUTO_APPROVAL_RATE
        AS OBSERVED_AUTO_APPROVAL_ERROR_RATE,
    0.05 AS APPROVED_AUTO_REJECTION_ERROR_LIMIT,
    CORRECT_MAPPING_REJECTION_RATE
        AS OBSERVED_AUTO_REJECTION_ERROR_RATE,
    AUTO_APPROVAL_ROWS,
    AUTO_REJECTION_ROWS,
    ENGINEERING_REVIEW_ROWS,
    CASE
        WHEN INCORRECT_AUTO_APPROVAL_RATE <= 0.02
         AND CORRECT_MAPPING_REJECTION_RATE <= 0.05
            THEN 'ACCEPTED_FOR_SHADOW_AUTOMATION'
        ELSE 'REJECTED_ON_TEST'
    END AS THRESHOLD_POLICY_STATUS,
    'The calibrated probability model is retained for shadow advisory scoring. Automatic approval and rejection are disabled because the locked test thresholds exceeded approved error limits.'
        AS DECISION_REASON,
    'SHADOW' AS DEPLOYMENT_MODE,
    FALSE AS OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    FALSE AS BUSINESS_DECISION_ALLOWED_FLAG,
    CURRENT_TIMESTAMP() AS DECIDED_AT
FROM KMAT_COST_MODEL_DB.CORE_ML.BMCS_TEST_EVALUATION_V2;

CREATE OR REPLACE VIEW BMCS_FINAL_TEST_SHADOW_OUTPUT_V2 AS
SELECT
    feature.ENTITY_ID,
    feature.RFQ_ID,
    feature.FEATURE_AS_OF_TIMESTAMP,
    feature.FEATURE_AS_OF_DATE,
    feature.SOURCE_LANGUAGE,
    feature.FEATURE_QUALITY_PASS_FLAG,
    feature.CORTEX_EXTRACTION_STATUS,
    feature.EXTRACTED_ENGINE,
    feature.EXTRACTED_CAB,
    feature.EXTRACTED_WHEEL,
    feature.EXTRACTED_COLOR,
    feature.RULE_BMCS_SCORE,
    feature.CORTEX_CONFIDENCE_SCORE,
    feature.DEVELOPMENT_HYBRID_BMCS_SCORE,
    prediction.RAW_ML_CORRECT_MAPPING_PROBABILITY,
    prediction.CALIBRATED_CORRECT_MAPPING_PROBABILITY,
    prediction.ML_BMCS_SCORE,
    IFF(
        prediction.ENTITY_ID IS NOT NULL,
        TRUE,
        FALSE
    ) AS ML_SCORING_COMPLETED_FLAG,
    CASE
        WHEN feature.FEATURE_QUALITY_PASS_FLAG = FALSE
            THEN 'FEATURE_QUALITY_GATE_FAILED'
        WHEN prediction.ENTITY_ID IS NULL
            THEN 'ML_PREDICTION_NOT_AVAILABLE'
        ELSE NULL
    END AS ML_FALLBACK_REASON,
    CASE
        WHEN prediction.ENTITY_ID IS NULL
            THEN 'DATA_QUALITY_FALLBACK'
        WHEN prediction.CALIBRATED_CORRECT_MAPPING_PROBABILITY
             >= 0.945
            THEN 'HIGH_CONFIDENCE_ADVISORY'
        WHEN prediction.CALIBRATED_CORRECT_MAPPING_PROBABILITY
             <= 0.485
            THEN 'LOW_CONFIDENCE_ADVISORY'
        ELSE 'MEDIUM_CONFIDENCE_ADVISORY'
    END AS ML_ADVISORY_TRUST_BAND,
    'ENGINEERING_REVIEW_REQUIRED'
        AS SHADOW_REVIEW_ACTION,
    'REJECTED_ON_TEST_FOR_AUTOMATION'
        AS THRESHOLD_POLICY_STATUS,
    'PHASE7_RULE_CORTEX_HYBRID'
        AS OFFICIAL_TRUST_SOURCE,
    'XGB_V1_BALANCED'
        AS EXPERIMENT_MODEL_NAME,
    'V2'
        AS EXPERIMENT_MODEL_VERSION,
    'ISOTONIC'
        AS CALIBRATION_METHOD,
    'BMCS_FEATURES_V2'
        AS FEATURE_SET_VERSION,
    'SYNTHETIC'
        AS TRAINING_DATA_CLASS,
    label.TARGET_CORRECT_MAPPING_FLAG,
    TRUE AS ML_ADVISORY_ONLY_FLAG,
    'SHADOW' AS DEPLOYMENT_MODE,
    FALSE AS OFFICIAL_COST_IMPACT_ALLOWED_FLAG,
    FALSE AS BUSINESS_DECISION_ALLOWED_FLAG,
    CURRENT_TIMESTAMP() AS CREATED_AT
FROM BMCS_FEATURE_DATASET_V2 feature
LEFT JOIN BMCS_TEST_PREDICTIONS_V2 prediction
  ON feature.ENTITY_ID = prediction.ENTITY_ID
LEFT JOIN BMCS_LABEL_DATASET_V2 label
  ON feature.ENTITY_ID = label.ENTITY_ID
WHERE feature.DATA_SPLIT = 'TEST';

