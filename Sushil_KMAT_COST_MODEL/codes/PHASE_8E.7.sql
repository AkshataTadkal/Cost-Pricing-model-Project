        TRY_TO_DOUBLE(s.CORTEX_EXTRACTION_SCORES:scores:COLOR:score::VARCHAR) AS COLOR_EXTRACTION_CONFIDENCE,

        h.RFQ_RECEIVED_AT,
        h.CREATED_AT AS RFQ_CREATED_AT,
        h.UPDATED_AT AS RFQ_UPDATED_AT,

        d.CHARACTERISTIC_ROW_COUNT,
        d.VALID_EXTRACTED_VALUE_COUNT,
        d.TEXT_SUPPORTED_VALUE_COUNT,
        d.UNSUPPORTED_VALUE_COUNT,
        COALESCE(d.ENGINE_TEXT_EVIDENCE_FLAG,0) AS ENGINE_TEXT_EVIDENCE_FLAG,
        COALESCE(d.CAB_TEXT_EVIDENCE_FLAG,0) AS CAB_TEXT_EVIDENCE_FLAG,
        COALESCE(d.WHEEL_TEXT_EVIDENCE_FLAG,0) AS WHEEL_TEXT_EVIDENCE_FLAG,
        COALESCE(d.COLOR_TEXT_EVIDENCE_FLAG,0) AS COLOR_TEXT_EVIDENCE_FLAG,
        d.LATEST_DETAIL_CREATED_AT,

        COALESCE(NULLIF(s.PROCESSING_TEXT_EN,''), NULLIF(s.SOURCE_DOCUMENT_TEXT,''), NULLIF(s.ORIGINAL_DOCUMENT_TEXT,''), '') AS PROCESSING_TEXT

    FROM KMAT_COST_MODEL_DB.CORE_ML.VW_RFQ_BMCS_STATUS_LATEST_V2 s
    LEFT JOIN KMAT_COST_MODEL_DB.CORE_INPUT.RFQ_HEADER h
      ON s.RFQ_ID = h.RFQ_ID
    LEFT JOIN KMAT_COST_MODEL_DB.CORE_ML.VW_BMCS_SCORING_DETAIL_AGG_V2 d
      ON s.RFQ_ID = d.RFQ_ID
     AND COALESCE(s.SIMULATION_ID,'__NO_SIMULATION__') = COALESCE(d.SIMULATION_ID,'__NO_SIMULATION__')
),
