    COUNT(DISTINCT ENTITY_ID) AS DISTINCT_ENTITIES,
    COUNT_IF(FEATURE_QUALITY_PASS_FLAG=TRUE) AS ML_ELIGIBLE_ROWS,
    COUNT_IF(FEATURE_QUALITY_PASS_FLAG=FALSE) AS FALLBACK_ROWS,
