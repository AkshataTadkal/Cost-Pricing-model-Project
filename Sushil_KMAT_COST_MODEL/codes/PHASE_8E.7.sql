    COUNT_IF(ML_ADVISORY_TRUST_BAND='OOD_ADVISORY') AS OOD_ADVISORY_ROWS,
    COUNT_IF(
        RAW_ML_PROBABILITY IS NOT NULL
        AND (RAW_ML_PROBABILITY<0 OR RAW_ML_PROBABILITY>1)
    ) AS INVALID_RAW_PROBABILITY_ROWS,
    COUNT_IF(
        CALIBRATED_ML_PROBABILITY IS NOT NULL
        AND (CALIBRATED_ML_PROBABILITY<0 OR CALIBRATED_ML_PROBABILITY>1)
    ) AS INVALID_CALIBRATED_PROBABILITY_ROWS,
    COUNT_IF(
        ML_BMCS_SCORE IS NOT NULL
        AND (ML_BMCS_SCORE<0 OR ML_BMCS_SCORE>100)
    ) AS INVALID_ML_SCORE_ROWS,
    COUNT_IF(SHADOW_REVIEW_ACTION<>'ENGINEERING_REVIEW_REQUIRED') AS INVALID_ACTION_ROWS,
    COUNT_IF(
        DEPLOYMENT_MODE<>'SHADOW'
        OR ML_ADVISORY_ONLY_FLAG<>TRUE
        OR OFFICIAL_COST_IMPACT_ALLOWED_FLAG<>FALSE
        OR BUSINESS_DECISION_ALLOWED_FLAG<>FALSE
    ) AS INVALID_AUTHORITY_ROWS
FROM BMCS_PHASE7_SHADOW_SCORE_FINAL_V2
WHERE SCORING_BATCH_ID='BMCS_PHASE7_SHADOW_001'
GROUP BY SCORING_BATCH_ID;


