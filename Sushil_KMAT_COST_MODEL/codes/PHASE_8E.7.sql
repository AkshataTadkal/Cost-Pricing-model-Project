SELECT
    RFQ_ID,
    SIMULATION_ID,
    COUNT(*) AS CHARACTERISTIC_ROWS,
    COUNT(DISTINCT CHARACTERISTIC_NAME) AS DISTINCT_CHARACTERISTICS
FROM VW_BMCS_SCORING_DETAIL_LATEST_V2
GROUP BY RFQ_ID, SIMULATION_ID
HAVING COUNT(*) > 4
    OR COUNT(*) <> COUNT(DISTINCT CHARACTERISTIC_NAME);

