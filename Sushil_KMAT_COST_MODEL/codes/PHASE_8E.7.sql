    SELECT
        B.*,
        RFQ_ID || '::' || COALESCE(SIMULATION_ID,'NO_SIMULATION') || '::V' || COALESCE(CONFIGURATION_VERSION::VARCHAR,'0') AS ENTITY_ID,
        COALESCE(CORTEX_PROCESSED_AT, LATEST_DETAIL_CREATED_AT, RFQ_UPDATED_AT, RFQ_CREATED_AT, RFQ_RECEIVED_AT) AS FEATURE_AS_OF_TIMESTAMP,
        LENGTH(PROCESSING_TEXT) AS DOCUMENT_LENGTH_CHARS,
        IFF(LENGTH(PROCESSING_TEXT)>0, GREATEST(1, CEIL(LENGTH(PROCESSING_TEXT)/1800.0)), 0) AS PAGE_COUNT,

        CASE
            WHEN LENGTH(PROCESSING_TEXT)=0 THEN 0.0
            WHEN UPPER(COALESCE(SOURCE_DOCUMENT_TYPE,'')) IN ('TEXT','TXT') THEN 0.98
            WHEN UPPER(COALESCE(SOURCE_DOCUMENT_TYPE,''))='PDF' THEN 0.90
            ELSE 0.85
        END AS OCR_QUALITY_SCORE,

        CASE
            WHEN UPPER(COALESCE(RFQ_COMPLEXITY_CATEGORY,''))='STANDARD_CONFIGURATION' THEN 30.0
            WHEN UPPER(COALESCE(RFQ_COMPLEXITY_CATEGORY,''))='CUSTOM_CONFIGURATION' THEN 70.0
            WHEN UPPER(COALESCE(RFQ_COMPLEXITY_CATEGORY,'')) IN ('COMPLEX_CONFIGURATION','HIGH_COMPLEXITY') THEN 90.0
            ELSE 50.0
        END AS DOCUMENT_COMPLEXITY_SCORE,

        REGEXP_COUNT(LOWER(COALESCE(CORTEX_EXTRACTION_REASONING,'') || ' ' || COALESCE(CORTEX_BMCS_REASONING,'')),
                     'unclear|ambiguous|inferred|not explicit|not fully|brief|does not explicitly') AS AMBIGUITY_TERM_COUNT,

        REGEXP_COUNT(LOWER(COALESCE(CORTEX_EXTRACTION_REASONING,'') || ' ' || COALESCE(CORTEX_BMCS_REASONING,'')),
                     'conflict|contradict|inconsistent|mismatch') AS CONFLICTING_PHRASE_COUNT,

        IFF(SOURCE_LANGUAGE<>'EN',1,0) AS TRANSLATION_USED_FLAG,
        CASE
            WHEN SOURCE_LANGUAGE='EN' THEN 1.0
            WHEN LENGTH(PROCESSING_TEXT)>0 AND NULLIF(TRIM(COALESCE(TRANSLATION_METHOD,'')),'') IS NOT NULL THEN 0.90
            WHEN LENGTH(PROCESSING_TEXT)>0 THEN 0.70
            ELSE 0.0
        END AS TRANSLATION_QUALITY_SCORE,

        IFF(LENGTH(PROCESSING_TEXT)>0,1,0) AS SOURCE_TEXT_PRESENT_FLAG,

        IFF(EXTRACTED_ENGINE IN ('V6','V8'),0,1)
        + IFF(EXTRACTED_CAB IN ('STANDARD','PREMIUM'),0,1)
        + IFF(EXTRACTED_WHEEL IN ('STANDARD','OFFROAD'),0,1)
        + IFF(EXTRACTED_COLOR IN ('RED','BLUE'),0,1) AS MISSING_REQUIREMENT_COUNT,

        IFF(ENGINE_TEXT_EVIDENCE_FLAG=1 AND POSITION(EXTRACTED_ENGINE IN UPPER(PROCESSING_TEXT))>0,1,0)
        + IFF(CAB_TEXT_EVIDENCE_FLAG=1 AND POSITION(EXTRACTED_CAB IN UPPER(PROCESSING_TEXT))>0,1,0)
        + IFF(WHEEL_TEXT_EVIDENCE_FLAG=1 AND POSITION(EXTRACTED_WHEEL IN UPPER(PROCESSING_TEXT))>0,1,0)
        + IFF(COLOR_TEXT_EVIDENCE_FLAG=1 AND POSITION(EXTRACTED_COLOR IN UPPER(PROCESSING_TEXT))>0,1,0) AS EXACT_PHRASE_MATCH_COUNT,

        LEAST(1.0, GREATEST(0.0,
            0.50 * (COALESCE(TEXT_SUPPORTED_VALUE_COUNT,0)/4.0)
            + 0.50 * COALESCE((ENGINE_EXTRACTION_CONFIDENCE+CAB_EXTRACTION_CONFIDENCE+WHEEL_EXTRACTION_CONFIDENCE+COLOR_EXTRACTION_CONFIDENCE)/4.0,0.0)
        )) AS SYNONYM_MATCH_STRENGTH,

        IFF(NULLIF(TRIM(COALESCE(CORTEX_EXTRACTION_REASONING,'')),'') IS NOT NULL,1,0) AS CORTEX_REASONING_AVAILABLE_FLAG,

        CASE
            WHEN UPPER(COALESCE(CORTEX_PROCESSING_STATUS,'')) LIKE '%COMPLETE%' AND COALESCE(CHARACTERISTIC_ROW_COUNT,0)=4 THEN 'COMPLETE'
            WHEN UPPER(COALESCE(CORTEX_PROCESSING_STATUS,'')) LIKE '%FAIL%' THEN 'FAILED'
            ELSE 'PARTIAL'
        END AS CORTEX_EXTRACTION_STATUS,

        COALESCE(RULE_BASED_BMCS_SCORE::FLOAT, BOM_MATCH_CONFIDENCE_SCORE::FLOAT, 0.0) AS RULE_BMCS_SCORE,
