        COALESCE(BOM_MATCH_CONFIDENCE_SCORE::FLOAT, RULE_BASED_BMCS_SCORE::FLOAT, CORTEX_BMCS_SCORE::FLOAT,0.0) AS DEVELOPMENT_HYBRID_BMCS_SCORE
    FROM B
