      'ACTUAL_DOWNTIME_MINUTES'
  );


-- Review work-center coverage in all splits.
SELECT
    WORK_CENTER_ID,
    DATA_SPLIT,
    COUNT(*) AS ROW_COUNT,
    AVG(TARGET_TDS_FACTOR) AS AVG_TDS_FACTOR,
    COUNT_IF(TARGET_TDS_FACTOR >= 2.0)
        AS HIGH_STRAIN_ROWS
FROM TDS_MODEL_DATASET_V2
GROUP BY WORK_CENTER_ID, DATA_SPLIT
ORDER BY WORK_CENTER_ID, DATA_SPLIT;


-- Benchmark deterministic rule performance.
SELECT
    DATA_SPLIT,

    AVG(
        ABS(
            DEVELOPMENT_RULE_BASELINE_FACTOR
            - TARGET_TDS_FACTOR
        )
    ) AS RULE_BASELINE_MAE,

    SQRT(
        AVG(
            POWER(
                DEVELOPMENT_RULE_BASELINE_FACTOR
                - TARGET_TDS_FACTOR,
                2
            )
        )
    ) AS RULE_BASELINE_RMSE,

    AVG(
        IFF(
            DEVELOPMENT_RULE_BASELINE_FACTOR
            < TARGET_TDS_FACTOR,
            1,
            0
        )
    ) AS RULE_UNDERPREDICTION_RATE

FROM TDS_MODEL_DATASET_V2
GROUP BY DATA_SPLIT
ORDER BY
    CASE DATA_SPLIT
        WHEN 'TRAIN' THEN 1
        WHEN 'VALIDATION' THEN 2
        WHEN 'TEST' THEN 3
        ELSE 4
    END;


