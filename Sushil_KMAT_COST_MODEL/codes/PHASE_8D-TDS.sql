CREATE OR REPLACE VIEW TDS_SYNTHETIC_SPLIT_V2 AS
SELECT
    r.*,

    CASE
        WHEN RUN_DATE <= TO_DATE('2024-12-31')
            THEN 'TRAIN'

        WHEN RUN_DATE <= TO_DATE('2025-06-30')
            THEN 'VALIDATION'

        WHEN RUN_DATE <= TO_DATE('2025-12-31')
            THEN 'TEST'

        ELSE 'EXCLUDED'
    END AS DATA_SPLIT,

    'SPLIT_V2' AS SPLIT_VERSION

FROM TDS_SYNTHETIC_RAW_V2 r;


MERGE INTO FEATURE_SET_REGISTRY target
USING (
    SELECT
        'TDS_FEATURES' AS FEATURE_SET_NAME,
        'V2' AS FEATURE_SET_VERSION,
        'REGRESSION' AS PREDICTION_TYPE,
        'ONE_OPERATION_RUN' AS ENTITY_GRAIN,
        'TARGET_TDS_FACTOR' AS TARGET_COLUMN_NAME,
        'CORE_ML.TDS_SYNTHETIC_SPLIT_V2'
            AS SOURCE_OBJECT_NAME,
        'DEVELOPMENT' AS STATUS,
        'Synthetic point-in-time TDS feature dataset. Post-run maintenance, tool replacement and downtime outcomes are excluded from prediction inputs.'
            AS NOTES
) source

ON target.FEATURE_SET_NAME = source.FEATURE_SET_NAME
AND target.FEATURE_SET_VERSION = source.FEATURE_SET_VERSION

WHEN MATCHED THEN UPDATE SET
    PREDICTION_TYPE = source.PREDICTION_TYPE,
    ENTITY_GRAIN = source.ENTITY_GRAIN,
    TARGET_COLUMN_NAME = source.TARGET_COLUMN_NAME,
    SOURCE_OBJECT_NAME = source.SOURCE_OBJECT_NAME,
    STATUS = source.STATUS,
    NOTES = source.NOTES

WHEN NOT MATCHED THEN INSERT (
    FEATURE_SET_NAME,
    FEATURE_SET_VERSION,
    PREDICTION_TYPE,
    ENTITY_GRAIN,
    TARGET_COLUMN_NAME,
    SOURCE_OBJECT_NAME,
    STATUS,
    NOTES
)
VALUES (
    source.FEATURE_SET_NAME,
    source.FEATURE_SET_VERSION,
    source.PREDICTION_TYPE,
    source.ENTITY_GRAIN,
    source.TARGET_COLUMN_NAME,
    source.SOURCE_OBJECT_NAME,
    source.STATUS,
    source.NOTES
);


CREATE OR REPLACE VIEW TDS_FEATURE_DATASET_V2 AS
SELECT
    OPERATION_RUN_ID AS ENTITY_ID,
    RUN_DATE AS FEATURE_AS_OF_DATE,
    TO_TIMESTAMP_NTZ(RUN_DATE) AS FEATURE_AS_OF_TIMESTAMP,

    DATA_SPLIT,
    'TDS_FEATURES' AS FEATURE_SET_NAME,
    'V2' AS FEATURE_SET_VERSION,
    'SYNTHETIC' AS SOURCE_DATA_CLASS,

    KMAT_ID,
    WORK_CENTER_ID,
    MACHINE_ID,
    OPERATION_ID,
    ENGINE,
    CAB,
    WHEEL,
    COLOR,

    MACHINE_AGE_YEARS,
    MACHINE_HOURS_RUN,
    PRE_RUN_VIBRATION_MM_S,
    PRE_RUN_TEMPERATURE_C,
    DAYS_SINCE_MAINTENANCE,
    TOOL_USAGE_CYCLES_PRE_RUN,
    SETUP_TIME_MINUTES,
    CONFIG_COMPLEXITY_SCORE,
    STANDARD_MAINTENANCE_COST_USD,

    SHIFT_LOAD_PCT,
    OPERATOR_EXPERIENCE_YEARS,
    RECENT_30D_DOWNTIME_MIN,
    PRIOR_30D_MAINTENANCE_COUNT,
    MACHINE_HEALTH_SCORE,
    PRIOR_30D_MEAN_VIBRATION_MM_S,
    PRIOR_WORK_CENTER_TDS_AVG,

    -- Development deterministic benchmark only.
    -- Do not replace the existing official TDS rule with this field.
    LEAST(
        3.5,
        GREATEST(
            1.0,

            1.0
            + IFF(ENGINE = 'V8', 0.10, 0)
            + IFF(CAB = 'PREMIUM', 0.08, 0)
            + IFF(WHEEL = 'OFFROAD', 0.12, 0)

            + IFF(PRE_RUN_VIBRATION_MM_S >= 6.5, 0.35,
                  IFF(PRE_RUN_VIBRATION_MM_S >= 4.5, 0.18, 0))

            + IFF(PRE_RUN_TEMPERATURE_C >= 82, 0.25,
                  IFF(PRE_RUN_TEMPERATURE_C >= 70, 0.12, 0))

            + IFF(DAYS_SINCE_MAINTENANCE >= 55, 0.25,
                  IFF(DAYS_SINCE_MAINTENANCE >= 35, 0.12, 0))

            + IFF(TOOL_USAGE_CYCLES_PRE_RUN >= 2200, 0.22,
                  IFF(TOOL_USAGE_CYCLES_PRE_RUN >= 1300, 0.10, 0))

            + IFF(MACHINE_HEALTH_SCORE < 55, 0.25,
                  IFF(MACHINE_HEALTH_SCORE < 70, 0.12, 0))

            + IFF(CONFIG_COMPLEXITY_SCORE >= 80, 0.18,
                  IFF(CONFIG_COMPLEXITY_SCORE >= 60, 0.08, 0))
        )
    ) AS DEVELOPMENT_RULE_BASELINE_FACTOR,

    ACTUAL_TDS_FACTOR AS TARGET_TDS_FACTOR,

    IFF(
        DATA_SPLIT IN ('TRAIN', 'VALIDATION', 'TEST')
        AND ACTUAL_TDS_FACTOR BETWEEN 1.0 AND 3.5,
        TRUE,
        FALSE
    ) AS TRAINING_ELIGIBLE_FLAG

FROM TDS_SYNTHETIC_SPLIT_V2;


