-- ============================================================
-- VALIDATION GATES
-- ============================================================

-- Expected:
-- TOTAL_ROWS = 24000
-- DISTINCT_ENTITY_IDS = 24000
-- NULL_TARGETS = 0
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT ENTITY_ID) AS DISTINCT_ENTITY_IDS,
    COUNT_IF(TARGET_TDS_FACTOR IS NULL) AS NULL_TARGETS,
    MIN(FEATURE_AS_OF_DATE) AS MIN_RUN_DATE,
    MAX(FEATURE_AS_OF_DATE) AS MAX_RUN_DATE
FROM TDS_MODEL_DATASET_V2;


-- Expected zero rows.
SELECT
    ENTITY_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM TDS_MODEL_DATASET_V2
GROUP BY ENTITY_ID
HAVING COUNT(*) > 1;


-- Expected:
-- TRAIN about 18000
-- VALIDATION about 3000
-- TEST about 3000
SELECT
    DATA_SPLIT,
    COUNT(*) AS ROW_COUNT,
    MIN(FEATURE_AS_OF_DATE) AS MIN_DATE,
    MAX(FEATURE_AS_OF_DATE) AS MAX_DATE,

    MIN(TARGET_TDS_FACTOR) AS MIN_TDS_FACTOR,
    MAX(TARGET_TDS_FACTOR) AS MAX_TDS_FACTOR,
    AVG(TARGET_TDS_FACTOR) AS AVG_TDS_FACTOR,

    COUNT_IF(TARGET_TDS_FACTOR >= 2.0)
        AS HIGH_STRAIN_ROWS,

    ROUND(
        100.0
        * COUNT_IF(TARGET_TDS_FACTOR >= 2.0)
        / COUNT(*),
        3
    ) AS HIGH_STRAIN_PCT

FROM TDS_MODEL_DATASET_V2
GROUP BY DATA_SPLIT
ORDER BY
    CASE DATA_SPLIT
        WHEN 'TRAIN' THEN 1
        WHEN 'VALIDATION' THEN 2
        WHEN 'TEST' THEN 3
        ELSE 4
    END;


-- Expected all null counts = 0.
SELECT
    COUNT_IF(WORK_CENTER_ID IS NULL) AS NULL_WORK_CENTER,
    COUNT_IF(MACHINE_ID IS NULL) AS NULL_MACHINE,
    COUNT_IF(OPERATION_ID IS NULL) AS NULL_OPERATION,
    COUNT_IF(PRE_RUN_VIBRATION_MM_S IS NULL) AS NULL_VIBRATION,
    COUNT_IF(PRE_RUN_TEMPERATURE_C IS NULL) AS NULL_TEMPERATURE,
    COUNT_IF(DAYS_SINCE_MAINTENANCE IS NULL) AS NULL_MAINTENANCE_AGE,
    COUNT_IF(MACHINE_HEALTH_SCORE IS NULL) AS NULL_MACHINE_HEALTH,
    COUNT_IF(PRIOR_WORK_CENTER_TDS_AVG IS NULL) AS NULL_PRIOR_TDS
FROM TDS_MODEL_DATASET_V2;


-- Expected zero rows.
SELECT COLUMN_NAME
